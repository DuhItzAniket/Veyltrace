"""End-to-end: synth-01…05 (and synth-05@silent) through the pipeline up to the Causatrix step.

R-00 acceptance (#9): the e2e run on synth passes through the Reason engines. The pipeline runs
infralume → … → faultloom → causatrix with the installed engines (stubs where a lane has not
landed yet), and the slate must validate and list the case's universe. The synth telemetry is
generated by core's adapter; VEYLTRACE_DATA and the runs root point into pytest's tmp_path.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from veyltrace_contracts import models
from veyltrace_core import io
from veyltrace_core.pipeline import run_case
from veyltrace_core.testing import FIXTURE_CODE_COMMIT, SYNTH_CASES, repo_root


@pytest.mark.parametrize("case", [*SYNTH_CASES, "synth-05@silent"])
def test_pipeline_through_causatrix(case: str, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("VEYLTRACE_DATA", str(tmp_path / "data"))
    summary = run_case(
        "synth",
        case,
        to_step="causatrix",
        runs_root=tmp_path / "runs",
        config_dir=repo_root() / "config",
        code_commit=FIXTURE_CODE_COMMIT,
    )
    assert summary.outcome == "ok", (summary.reason, summary.failed_step)
    result = next(r for r in summary.results if r.engine == "causatrix")
    assert result.status == "ok"
    assert not any(n.startswith("stub: ") for n in result.notes)
    slate = io.read_model("slate", summary.run_dir, models.Slate, validate=True)
    manifest = io.read_model("case_manifest", summary.run_dir, models.CaseManifest)
    assert slate.case_id == manifest.case_id == summary.case_id
    services = {s.service for s in slate.all_scores}
    assert set(manifest.services) <= services  # every manifest service is in U
    # 07 §3.1: no ranker voted -> empty slate; otherwise the top min(K, |U|) services.
    assert len(slate.candidates) == (min(slate.k, len(services)) if slate.rankers_active else 0)
