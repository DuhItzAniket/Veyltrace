"""Lane ownership checks. Source of truth: .github/lanes.yml.

Usage:
  uv run scripts/check_lanes.py --lane observe            # check your branch vs origin/main
  uv run scripts/check_lanes.py --author <login> --labels "lane:observe,agent:codex" --base origin/main
  uv run scripts/check_lanes.py --write-codeowners         # regenerate .github/CODEOWNERS
  uv run scripts/check_lanes.py --verify-codeowners        # CI: CODEOWNERS matches lanes.yml

Why: three people with three different AI agents conflict most on structural edits
(add/add, modify/delete). Keeping each lane inside its own paths removes most of them.
See docs/08-collaboration-and-git.md.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

import pathspec
import yaml

ROOT = Path(__file__).resolve().parent.parent
LANES_FILE = ROOT / ".github" / "lanes.yml"
CODEOWNERS_FILE = ROOT / ".github" / "CODEOWNERS"
PLACEHOLDER = re.compile(r"^[A-Z0-9_]+$")


def load() -> dict:
    with LANES_FILE.open(encoding="utf-8") as f:
        return yaml.safe_load(f)


def lane_of(path: str, cfg: dict) -> str:
    """Return 'shared' or the first lane whose patterns match `path`."""
    shared = pathspec.PathSpec.from_lines("gitwildmatch", cfg.get("shared", []))
    if shared.match_file(path):
        return "shared"
    for lane, patterns in cfg["lanes"].items():
        if pathspec.PathSpec.from_lines("gitwildmatch", patterns).match_file(path):
            return lane
    raise SystemExit(f"lanes.yml has no catch-all lane; unmatched path: {path}")


def changed_files(base: str) -> list[str]:
    out = subprocess.run(
        ["git", "diff", "--name-only", f"{base}...HEAD"],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout
    return sorted(p for p in out.splitlines() if p.strip())


def check(lane: str, base: str, labels: set[str], cfg: dict) -> int:
    if lane not in cfg["lanes"]:
        print(f"Unknown lane '{lane}'. Known: {', '.join(cfg['lanes'])}")
        return 2
    files = changed_files(base)
    outside = [(f, lane_of(f, cfg)) for f in files]
    outside = [(f, owner) for f, owner in outside if owner not in (lane, "shared")]
    if not outside:
        print(f"OK: {len(files)} changed file(s), all inside lane '{lane}' or shared paths.")
        return 0
    if "cross-lane" in labels:
        print("cross-lane label present; files outside the lane (reviewer must be that lane's owner):")
        for f, owner in outside:
            print(f"  {f}  (owned by {owner})")
        return 0
    print(f"FAIL: lane '{lane}' changed files owned by other lanes:")
    for f, owner in outside:
        print(f"  {f}  (owned by {owner})")
    print("Move these edits to an issue for the owning lane, or ask the lead for the 'cross-lane' label.")
    return 1


def to_codeowners_pattern(glob: str) -> str:
    if glob == "**":
        return "*"
    if glob.endswith("/**"):
        return "/" + glob[:-3] + "/"
    return "/" + glob


def render_codeowners(cfg: dict) -> str:
    members: dict[str, str] = cfg["members"]
    real = {login: lane for login, lane in members.items() if not PLACEHOLDER.match(login)}
    lead = cfg["lead"]
    everyone = sorted(real)

    def owners(lane: str) -> str:
        if lane == "reason":
            # Everyone co-owns the lead's paths so the lead's own PRs can be approved by someone else.
            names = [lead, *[n for n in everyone if n != lead]]
        else:
            # Lane member(s) plus the lead, so either can approve that lane's PRs.
            names = sorted({lead, *[n for n, ln in real.items() if ln == lane]})
        return " ".join(f"@{n}" for n in names)

    lines = [
        "# GENERATED by scripts/check_lanes.py --write-codeowners from .github/lanes.yml. Do not edit by hand.",
        "# Last matching pattern wins, so the catch-all comes first.",
        "",
    ]
    order = ["reason"] + [ln for ln in cfg["lanes"] if ln != "reason"]
    for lane in order:
        lines.append(f"# lane: {lane}")
        for glob in cfg["lanes"][lane]:
            lines.append(f"{to_codeowners_pattern(glob)} {owners(lane)}")
        lines.append("")
    lines.append("# shared, author-owned files")
    for glob in cfg.get("shared", []):
        lines.append(f"{to_codeowners_pattern(glob)} {' '.join('@' + n for n in everyone)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lane")
    ap.add_argument("--author", help="GitHub login of the PR author (CI)")
    ap.add_argument("--labels", default="", help="comma-separated PR labels (CI)")
    ap.add_argument("--base", default="origin/main")
    ap.add_argument("--write-codeowners", action="store_true")
    ap.add_argument("--verify-codeowners", action="store_true")
    args = ap.parse_args()
    cfg = load()

    if args.write_codeowners:
        CODEOWNERS_FILE.write_text(render_codeowners(cfg), encoding="utf-8", newline="\n")
        print(f"wrote {CODEOWNERS_FILE.relative_to(ROOT)}")
        return 0
    if args.verify_codeowners:
        current = CODEOWNERS_FILE.read_text(encoding="utf-8") if CODEOWNERS_FILE.exists() else ""
        if current != render_codeowners(cfg):
            print("FAIL: .github/CODEOWNERS is out of date. Run: uv run scripts/check_lanes.py --write-codeowners")
            return 1
        print("OK: CODEOWNERS matches lanes.yml")
        return 0

    labels = {l.strip() for l in args.labels.split(",") if l.strip()}
    lane = args.lane
    if args.author:
        lane = cfg["members"].get(args.author)
        if lane is None:
            # Unknown author (placeholder logins not yet filled, or a bot such as Copilot's cloud agent):
            # fall back to the PR's lane label so the path check still applies.
            lane_labels = sorted(l.split(":", 1)[1] for l in labels if l.startswith("lane:"))
            if len(lane_labels) != 1:
                print(f"FAIL: author '{args.author}' is not in lanes.yml members and the PR has "
                      f"{len(lane_labels)} lane:* labels. Add exactly one lane:<lane> label.")
                return 1
            lane = lane_labels[0]
            print(f"Author '{args.author}' not in members; using label lane:{lane}.")
    if not lane:
        ap.error("give --lane or --author")
    return check(lane, args.base, labels, cfg)


if __name__ == "__main__":
    sys.exit(main())
