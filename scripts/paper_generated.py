@dataclass
class Build:
    files: dict[str, bytes]  # file name in paper/generated/ -> bytes
    resolved: dict[tuple[str, str], str]
    unresolved: dict[tuple[str, str], str]  # (key, selector) -> reason
    invalid: list[str]  # \resnum uses that do not parse
    uses: list[Use]
    tables: int = 0  # every copied table file: <name>.tex, -paper.tex and -full.tex
    figures: int = 0
    panels: int = 0
    views: int = 0  # -paper.tex among them
    grids: int = 0  # -full.tex among them


def numbers_tex(resolved: Mapping[tuple[str, str], str], unresolved: Mapping[tuple[str, str], str]) -> str:
    lines = [
        HEADER.rstrip("\n"),
        f"% {len(resolved)} of {len(resolved) + len(unresolved)} \\resnum keys resolve.",
    ]
    lines += [f"\\defresnum{{{k}}}{{{s}}}{{{v}}}" for (k, s), v in sorted(resolved.items())]
    lines += [f"% unresolved: {k} | {s}: {why}" for (k, s), why in sorted(unresolved.items())]
    return "\n".join(lines) + "\n"


def build(root: Path, tracked: frozenset[str] | None) -> Build:
    """Everything paper/generated/ should hold, from the committed results under `root`."""
    results = root / RESULTS
    files: dict[str, bytes] = {}

    def add(name: str, data: bytes) -> None:
        if name in files:
            raise ConversionError(f"two generated files are named {name}")
        files[name] = data

    tables = (
        sorted((results / "tables").glob("*.tex"), key=lambda p: p.name)
        if (results / "tables").is_dir()
        else []
    )
    for table in tables:
        add(table.name, table.read_bytes())
    figures = group_figures(results / "figures")
    for name, svgs in figures.items():
        panels = [(s.name, s.read_text(encoding="utf-8")) for s in svgs]
        add(f"{name}.tex", figure_tex(panels).encode("utf-8"))
    uses, invalid = scan_uses(root / SECTIONS)
    resolver = Resolver(results, root / EXPERIMENTS, tracked)
    resolved: dict[tuple[str, str], str] = {}
    unresolved: dict[tuple[str, str], str] = {}
    for use in uses:
        try:
            resolved[(use.key, use.selector)] = resolver.resolve(use.key, use.selector)
        except Unresolved as e:
            unresolved[(use.key, use.selector)] = e.reason
        except SelectorError as e:
            invalid.append(f"{use.where}: {e}")
    add(NUMBERS, numbers_tex(resolved, unresolved).encode("utf-8"))
    return Build(
        files,
        resolved,
        unresolved,
        invalid,
        uses,
        tables=len(tables),
        figures=len(figures),
        panels=sum(len(v) for v in figures.values()),
        views=sum(t.name.endswith(f"{PAPER_SUFFIX}.tex") for t in tables),
        grids=sum(t.name.endswith(f"{FULL_SUFFIX}.tex") for t in tables),
    )


def tracked_files(root: Path) -> frozenset[str] | None:
    """The bench/results paths git tracks with the content of HEAD: a value comes from committed
    files only, so a tracked file edited or staged since the last commit does not count."""

    def git(*args: str) -> set[str]:
        out = subprocess.run(
            ["git", "-C", str(root), *args, "--", RESULTS.as_posix()], capture_output=True, check=True
        )
        return {p for p in out.stdout.decode("utf-8").split("\0") if p}

    return frozenset(git("ls-files", "-z") - git("diff", "--name-only", "-z", "HEAD"))


def write(target: Path, files: Mapping[str, bytes]) -> tuple[int, int]:
    """Write changed files and remove generated .tex files this step no longer produces."""
    target.mkdir(parents=True, exist_ok=True)
    changed = removed = 0
    for name, data in sorted(files.items()):
        path = target / name
        if not path.is_file() or path.read_bytes() != data:
            path.write_bytes(data)
            changed += 1
    for stale in sorted(target.glob("*.tex")):
        if stale.name not in files:
            stale.unlink()
            removed += 1
    return changed, removed


def report(out: Build, emit: Callable[[str], object] = print) -> None:
    n = len(out.uses)
    emit(
        f"paper/generated: {out.tables - out.views - out.grids} tables ({out.views} paper views, "
        f"{out.grids} full grids), {out.figures} figures ({out.panels} SVG panels as TikZ), "
        f"numbers.tex: {len(out.resolved)} of {n} \\resnum keys resolve"
    )
    if out.unresolved:
        emit(f"unresolved ({len(out.unresolved)}; the PDF prints a red blank for each):")
        where = {(u.key, u.selector): u.where for u in out.uses}
        for (k, s), why in sorted(out.unresolved.items()):
            emit(f"  {where[(k, s)]}  {k} | {s}: {why}")
    if out.invalid:
        emit(f"invalid ({len(out.invalid)}):")
        for line in out.invalid:
            emit(f"  {line}")


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n", 1)[0])
    parser.add_argument(
        "--check", action="store_true", help="write nothing; exit 1 if a \\resnum is unresolved"
    )
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root (default: this checkout)")
    args = parser.parse_args(list(argv) if argv is not None else None)
    for stream in (sys.stdout, sys.stderr):  # reasons quote not_run.yaml (§, –): never the console codepage
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")  # pyright: ignore[reportAttributeAccessIssue]  # TextIO lacks it; TextIOWrapper has it
    root: Path = args.root.resolve()
    try:
        out = build(root, tracked_files(root))
    except ConversionError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    report(out)
    if args.check:
        return 1 if out.unresolved or out.invalid else 0
    changed, removed = write(root / GENERATED, out.files)
    print(f"wrote {changed} changed file(s), removed {removed} stale file(s) in {GENERATED.as_posix()}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
