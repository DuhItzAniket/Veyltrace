"""Fill paper/generated/ from committed bench results (R-17 copy step, #46).

Usage: `uv run python scripts/paper_generated.py [--check] [--root DIR]` from the repository root,
then `latexmk` in paper/ (paper/README.md, "Build").

Why: the paper types no result number by hand (AGENTS.md §4.8, docs/11 §10). This step writes
three kinds of file into paper/generated/, which nobody edits and git ignores:

- `<name>.tex` for every table: a byte copy of R-17's `bench/results/tables/<name>.tex`, with its
  full grid `<name>-full.tex` (a longtable, `\\resulttablefull`) and, for a table the main text
  cites, its compact paper view `<name>-paper.tex`, which `\\resulttable` prefers.
- `<name>.tex` for every figure: R-17's `bench/results/figures/<name>[-<panel>].svg` panels
  converted to TikZ, one `tikzpicture` per panel, which `\\resultfigure` lays out. The converter
  knows exactly the elements and attributes `veyltrace_bench.tables.svg` writes; anything else is
  an error, never dropped, so a figure in the PDF always shows everything the SVG shows.
- `numbers.tex`: `\\defresnum{<key>}{<selector>}{<value>}` for every `\\resnum` in
  paper/sections/*.tex that resolves against committed results, sorted. A key that does not
  resolve (not run, revised, missing file, null value) stays undefined, so the PDF prints its red
  blank; the report names it and why. paper/README.md defines the selector grammar and formats.

Values are read, never estimated: the only arithmetic is the point difference between two
experiments' committed values (`difference/vs:`, `max_drop/vs:`). `--check` writes nothing and
exits 1 when any `\\resnum` is unresolved or unparseable.
"""

