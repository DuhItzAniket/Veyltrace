SELECTOR_CHARS = re.compile(r"^[A-Za-z0-9_:.,/-]+$")
INTEGER_LEAF = re.compile(r"(?:^|_)(?:ms|mb)(?:_|$)|^(?:tokens|turns)_")  # ms, MiB, tokens, turns
P_LEAF = re.compile(r"(?:^|_)p$")  # holm_p, sign_flip_p, mcnemar_p


Obj = dict[str, object]  # a JSON object as json.loads returns it


def _obj(value: object) -> Obj | None:
    return cast(Obj, value) if isinstance(value, dict) else None


def _rows(value: object) -> list[Obj]:
    """The objects of a JSON list (an absent or non-list value has none)."""
    items = cast(list[object], value) if isinstance(value, list) else []
    return [o for o in map(_obj, items) if o is not None]


class SelectorError(ValueError):
    """A selector that does not follow the grammar of paper/README.md."""


class Unresolved(LookupError):
    """A well-formed key whose value is not in the committed results; the message says why."""

    @property
    def reason(self) -> str:
        return str(self.args[0])


class ConversionError(ValueError):
    """An SVG the TikZ converter cannot draw exactly."""


# ------------------------------------------------------------------------------- selectors


@dataclass(frozen=True)
class Selector:
    """`<system>/<method>[-vs-<method>]/<metric>[/<part>[/vs:<id>[,<id>…]]]` (paper/README.md)."""

    system: str
    method_a: str
    method_b: str | None
    metric: str
    part: str | None
    vs: tuple[str, ...] = ()


def parse_selector(text: str) -> Selector:
    """Parse an experiment selector; a form the grammar does not define is a SelectorError."""
    if not SELECTOR_CHARS.match(text):
        raise SelectorError(f"{text!r}: only letters, digits and _ : . , / - are allowed")
    parts = text.split("/")
    if len(parts) < 3 or not all(parts[:3]):
        raise SelectorError(f"{text!r}: expected <system>/<method>/<metric>[/<part>]")
    system, method, metric, rest = parts[0], parts[1], parts[2], parts[3:]
    a, _, b = method.partition(VS)
    if not a or (VS in method and not b):
        raise SelectorError(f"{text!r}: a comparison is <a>-vs-<b>")
    method_b = b or None
    if not rest:
        if method_b is not None:
            raise SelectorError(f"{text!r}: a comparison needs /difference, /ci or /holm_p")
        return Selector(system, a, method_b, metric, None)
    if len(rest) == 1 and rest[0] in PARTS:
        if rest[0] in ("difference", "holm_p") and method_b is None:
            raise SelectorError(f"{text!r}: {rest[0]} needs <a>-vs-<b>, or /vs:<id> for experiments")
        return Selector(system, a, method_b, metric, rest[0])
    if len(rest) == 2 and rest[0] in CROSS_PARTS and rest[1].startswith("vs:"):
        ids = tuple(rest[1].removeprefix("vs:").split(","))
        if not all(ids):
            raise SelectorError(f"{text!r}: vs: needs experiment ids")
        if method_b is not None:
            raise SelectorError(f"{text!r}: a comparison <a>-vs-<b> is within one experiment")
        if rest[0] == "difference" and len(ids) != 1:
            raise SelectorError(f"{text!r}: difference/vs: names one experiment")
        return Selector(system, a, None, metric, rest[0], ids)
    raise SelectorError(f"{text!r}: unknown part {'/'.join(rest)!r} (ci, difference, holm_p, .../vs:<id>)")


# ------------------------------------------------------------------------------- formatting


def _sign(text: str) -> str:
    """A typographic minus, so a negative value never prints as a hyphen."""
    return "\\ensuremath{-}" + text[1:] if text.startswith("-") else text


def _significant(value: float, digits: int) -> str:
    """`value` rounded ROUND_HALF_UP to `digits` significant digits, in fixed-point notation."""
    d = Decimal(repr(float(value)))
    if d == 0:
        return "0"
    exp = d.adjusted()
    q = d.quantize(Decimal(1).scaleb(exp - digits + 1), rounding=ROUND_HALF_UP)
    if q.adjusted() > exp:  # 0.0009999 rounds up to 0.00100: one digit fewer after the point
        q = d.quantize(Decimal(1).scaleb(exp - digits + 2), rounding=ROUND_HALF_UP)
    return format(q, "f")


def format_value(value: object, leaf: str, *, p: bool = False, signed: bool = False) -> str:
    """The printed form of one committed value: rates and differences with 3 decimals as the
    tables print them (`cells.fixed`, ROUND_HALF_UP), ms / MiB / tokens / turns and JSON integers
    as integers, p-values with 3 significant digits."""
    if isinstance(value, bool) or not isinstance(value, int | float):
        raise Unresolved(f"{leaf} is {'null' if value is None else type(value).__name__}, not a number")
    if isinstance(value, int):
        return _sign(str(value))
    if p or P_LEAF.search(leaf):
        return _sign(_significant(value, P_SIGNIFICANT))
    digits = 0 if INTEGER_LEAF.search(leaf) else RATE_DIGITS
    return _sign(fixed(value, digits, signed=signed))


def format_interval(low: object, high: object, leaf: str) -> str:
    """`[low, high]`; a bound that rounds to zero keeps its sign, as in the tables."""
    return f"[{format_value(low, leaf, signed=True)}, {format_value(high, leaf, signed=True)}]"


# ------------------------------------------------------------------------------- resolution


def _number(value: object, what: str) -> int | float:
    """A committed number as JSON typed it: an int (a count) stays an int."""
    if isinstance(value, bool) or not isinstance(value, int | float):
        raise Unresolved(f"{what} is {'null' if value is None else type(value).__name__}, not a number")
    return value


@dataclass
class Resolver:
    """Looks up `\\resnum` keys in committed results. `tracked` is the set of repository-relative
    POSIX paths git tracks under bench/results (None: no check, for tests)."""

    results: Path
    experiments: Path
    tracked: frozenset[str] | None
    _json: dict[Path, object] = field(default_factory=dict[Path, object])

    def __post_init__(self) -> None:
        register = read_register(self.results)
        self.reasons, self.revises = register.reasons, register.revises

    # -- files

    def _load(self, path: Path, label: str) -> object:
        if path not in self._json:
            if not path.is_file():
                raise Unresolved(f"no committed {label}")
            if self.tracked is not None:
                rel = (RESULTS / path.relative_to(self.results)).as_posix()
                if rel not in self.tracked:
                    raise Unresolved(
                        f"{label} is not committed (git does not track it, or it differs from HEAD)"
                    )
            self._json[path] = json.loads(path.read_text(encoding="utf-8"))
        return self._json[path]

    def _summary(self, exp: str) -> Obj:
        if exp in self.reasons:
            raise Unresolved(f"not run: {self.reasons[exp]}")
        revisions = sorted(r for r, pre in self.revises.items() if pre == exp)
        if revisions:
            raise Unresolved(f"revised by {', '.join(revisions)} (04 §12); key the prose to the revision")
        if not (self.experiments / f"{exp}.yaml").is_file():
            raise Unresolved(f"no bench/experiments/{exp}.yaml: not an experiment id")
        data = _obj(self._load(self.results / exp / "summary.json", f"bench/results/{exp}/summary.json"))
        if data is None:
            raise Unresolved(f"bench/results/{exp}/summary.json is not an object")
        return data

    def _statistics(self, exp: str, summary: Obj, table: str) -> list[Obj]:
        raw = summary.get("statistics")
        st = _obj(raw)
        if st is None:
            raise Unresolved(f"{exp} has no statistics ({raw!r})")
        if not isinstance(st.get(table), list):
            raise Unresolved(f"{exp} statistics has no {table}")
        return _rows(st.get(table))

    # -- one value

    def resolve(self, key: str, selector: str) -> str:
        """The printed value of `\\resnum{key}{selector}`; Unresolved says why there is none."""
        side = self._side(key)
        if side is not None:
            return self._json_path(side, key, selector)
        s = parse_selector(selector)
        leaf = s.metric.split(".")[-1]
        if s.vs:  # a point difference between experiments
            ref = self._point(key, s)
            others: list[int | float] = []
            for other in s.vs:
                try:
                    others.append(self._point(other, s))
                except Unresolved as e:
                    raise Unresolved(f"{other}: {e.reason}") from None
            if s.part == "difference":  # the change in the named experiment against the reference
                return format_value(_difference(others[0], ref), leaf)
            return format_value(max(_difference(ref, o) for o in others), leaf)
        if s.method_b is not None:
            return self._comparison(key, s, leaf)
        if s.part == "ci":
            row = self._interval(key, s, leaf)
            return format_interval(row.get("low"), row.get("high"), leaf)
        return format_value(self._raw_point(key, s), leaf)

    def _point(self, exp: str, s: Selector) -> int | float:
        return _number(self._raw_point(exp, s), f"{exp} {s.system}/{s.method_a}/{s.metric}")

    def _raw_point(self, exp: str, s: Selector) -> object:
        if s.system == POOLED:  # no pooled group: the pooled interval row's point estimate
            return self._interval(exp, s, s.metric.split(".")[-1]).get("estimate")
        summary = self._summary(exp)
        groups = [
            g
            for g in _rows(summary.get("groups"))
            if g.get("system") == s.system and g.get("method") == s.method_a
        ]
        if len(groups) != 1:
            raise Unresolved(
                f"{'no' if not groups else 'more than one'} group {s.system}/{s.method_a} in {exp}"
            )
        return _group_value(groups[0], s.metric, f"{exp} {s.system}/{s.method_a}")

    def _interval(self, exp: str, s: Selector, leaf: str) -> Obj:
        summary = self._summary(exp)
        system = None if s.system == POOLED else s.system
        rows = [
            r
            for r in self._statistics(exp, summary, "intervals")
            if r.get("system") == system and r.get("method") == s.method_a and r.get("metric") == leaf
        ]
        if len(rows) != 1:
            many = "more than one" if rows else "no"
            raise Unresolved(f"{many} interval for {s.system}/{s.method_a}/{leaf} in {exp}")
        return rows[0]

    def _comparison(self, exp: str, s: Selector, leaf: str) -> str:
        summary = self._summary(exp)  # first: not run, revised and missing files say so
        if s.method_b == BEST:
            declared = _noninferiority_vs(self.experiments / f"{exp}.yaml")
            if declared != BEST:
                raise Unresolved(f"{exp} compares against {declared!r}, not {BEST}")
        system = None if s.system == POOLED else s.system
        rows = [
            r
            for r in self._statistics(exp, summary, "comparisons")
            if r.get("system") == system
            and r.get("method_a") == s.method_a
            and (s.method_b == BEST or r.get("method_b") == s.method_b)
            and r.get("metric") == leaf
        ]
        if not rows:
            raise Unresolved(f"no comparison {s.system}/{s.method_a}-vs-{s.method_b}/{leaf} in {exp}")
        if s.part == "holm_p":
            rows = [r for r in rows if r.get("holm_p") is not None]
            values = {format_value(r.get("holm_p"), "holm_p", p=True) for r in rows}
        elif s.part == "ci":
            values = {format_interval(r.get("low"), r.get("high"), leaf) for r in rows}
        else:
            values = {format_value(r.get("difference"), leaf) for r in rows}
        if len(values) != 1:
            raise Unresolved(f"{len(values)} values for {s.part} of {s.system}/{s.method_a}-vs-{s.method_b}")
        return values.pop()

    # -- side results

    def _side(self, key: str) -> Path | None:
        for prefix, template in SIDE_RESULTS.items():
            if prefix.endswith("/") and key.startswith(prefix) and len(key) > len(prefix):
                rest = key.removeprefix(prefix)
                if rest in self.reasons:
                    raise Unresolved(f"not run: {self.reasons[rest]}")
                return self.results / template.format(rest)
            if key == prefix:
                return self.results / template
        return None

    def _json_path(self, path: Path, key: str, selector: str) -> str:
        """A dotted JSON path (a list index is a number); a final `ci` prints the object's
        `low`/`high` or `ci_low`/`ci_high` as an interval."""
        if not SELECTOR_CHARS.match(selector) or "/" in selector or "" in selector.split("."):
            raise SelectorError(f"{selector!r}: a side result takes a dotted JSON path")
        node = self._load(path, f"bench/results/{path.relative_to(self.results).as_posix()}")
        names = selector.split(".")
        leaf = key
        for i, name in enumerate(names):
            obj = _obj(node)
            if obj is not None and name == "ci" and i == len(names) - 1:
                for low, high in (("low", "high"), ("ci_low", "ci_high")):
                    if low in obj and high in obj:
                        return format_interval(obj[low], obj[high], leaf)
            items = cast(list[object], node) if isinstance(node, list) else None
            if obj is not None and name in obj:
                node, leaf = obj[name], name
            elif items is not None and name.isdigit() and int(name) < len(items):
                node = items[int(name)]
            else:
                raise Unresolved(f"no key {'.'.join(names[: i + 1])!r} in {key}")
        return format_value(node, leaf)


def _difference(a: int | float, b: int | float) -> int | float:
    """`a - b` of two committed values, exact in decimal on the values as the files write them
    (`repr`, the tables' rounding rule), so 0.4005 - 0.342 rounds to 0.059 as a reader subtracting
    the files by hand gets, never to the 0.058 of the binary float 0.058499999999999996. Two JSON
    integers (counts) give an integer; any float input gives a float, so a rate difference of
    1.0 - 1.0 prints as 0.000, not as the count 0."""
    if isinstance(a, int) and isinstance(b, int):
        return a - b
    return float(Decimal(repr(float(a))) - Decimal(repr(float(b))))


def _group_value(group: Obj, metric: str, where: str) -> object:
    """A group's value for a metric path: `outcomes.<o>`, a top-level `n_*` count, `<entry>.<key>`,
    or `<key>` alone when one entry holds it (ac_at_1) or the entry is named as its key."""
    names = metric.split(".")
    if names[0] == "outcomes" and len(names) == 2:
        outcomes = _obj(group.get("outcomes"))
        if outcomes is not None and names[1] in outcomes:
            return outcomes[names[1]]
        raise Unresolved(f"no outcome {names[1]!r} in {where}")
    if len(names) == 1 and names[0].startswith("n_") and names[0] in group:
        return group[names[0]]
    metrics = _obj(group.get("metrics"))
    if metrics is None or len(names) > 2:
        raise Unresolved(f"no metric {metric} in {where}")
    if len(names) == 2:
        entry_name, key = names
    elif names[0] in metrics:
        entry_name = key = names[0]
    else:
        owners = sorted(e for e, v in metrics.items() if names[0] in (_obj(v) or {}))
        if len(owners) != 1:
            raise Unresolved(f"no metric {metric} in {where}")
        entry_name, key = owners[0], names[0]
    if entry_name not in metrics:
        raise Unresolved(f"no metric {metric} in {where}")
    if metrics[entry_name] is None:
        raise Unresolved(f"{entry_name} is null in {where} (undefined for this group)")
    entry = _obj(metrics[entry_name])
    if entry is None or key not in entry:
        raise Unresolved(f"no metric {metric} in {where}")
    value = entry[key]
    if value is None:
        raise Unresolved(f"{entry_name}.{key} is null in {where} (undefined for this group)")
    return value


def _noninferiority_vs(path: Path) -> str | None:
    """`statistics.noninferiority.vs` of an experiment YAML: who `best_simple_baseline` is for."""
    import yaml

    data = _obj(yaml.safe_load(path.read_text(encoding="utf-8"))) or {}
    ni = _obj((_obj(data.get("statistics")) or {}).get("noninferiority")) or {}
    vs = ni.get("vs")
    return str(vs) if vs is not None else None


# ------------------------------------------------------------------------------- \resnum uses

RESNUM = re.compile(r"\\resnum(?![A-Za-z@])")
RESNUM_ARGS = re.compile(r"\\resnum\s*\{([^{}]*)\}\s*\{([^{}]*)\}")
COMMENT = re.compile(r"(?<!\\)%.*")


@dataclass(frozen=True)
class Use:
    key: str
    selector: str
    where: str  # file:line of the first use


def scan_uses(sections: Path) -> tuple[list[Use], list[str]]:
    """Every distinct `\\resnum{key}{selector}` outside TeX comments, in file and line order of
    first use, and the places where `\\resnum` is not followed by two plain arguments."""
    uses: dict[tuple[str, str], Use] = {}
    bad: list[str] = []
    for path in sorted(sections.glob("*.tex"), key=lambda p: p.name):
        lines = path.read_text(encoding="utf-8").splitlines()
        text = "\n".join(COMMENT.sub("", line) for line in lines)
        for m in RESNUM.finditer(text):
            where = f"{path.name}:{text.count(chr(10), 0, m.start()) + 1}"
            args = RESNUM_ARGS.match(text, m.start())
            if args is None:
                bad.append(f"{where}: \\resnum without two plain arguments")
                continue
            pair = (args.group(1).strip(), args.group(2).strip())
            uses.setdefault(pair, Use(*pair, where))
    return list(uses.values()), bad


# ------------------------------------------------------------------------------- SVG -> TikZ

SVG_NS = "{http://www.w3.org/2000/svg}"
NUM = re.compile(r"^-?(?:\d+(?:\.\d*)?|\.\d+)$")
ROTATE = re.compile(r"^rotate\((\S+?)(?:[ ,]+(\S+?)[ ,]+(\S+?))?\)$")
FAMILIES = {"sans-serif": "\\sffamily", "serif": "\\rmfamily", "monospace": "\\ttfamily"}
ANCHORS = {"start": "base west", "middle": "base", "end": "base east"}
#: Attributes each element may carry, as svg.py writes them; any other is a ConversionError.
ALLOWED = {
    "rect": {"x", "y", "width", "height", "fill", "stroke", "stroke-width"},
    "line": {"x1", "y1", "x2", "y2", "stroke", "stroke-width"},
    "circle": {"cx", "cy", "r", "fill", "stroke", "stroke-width"},
    "polyline": {"points", "fill", "stroke", "stroke-width"},
    "path": {"d", "fill", "stroke", "stroke-width"},
    "text": {"x", "y", "text-anchor", "fill", "transform"},
    "title": set[str](),
}


def _num(el: ET.Element, name: str, source: str) -> str:
    value = el.get(name)
    if value is None or not NUM.match(value):
        raise ConversionError(f"{source}: <{_tag(el)}> {name}={value!r} is not a plain number")
    return value


def _tag(el: ET.Element) -> str:
    return el.tag.removeprefix(SVG_NS)


def _colour(value: str | None, source: str) -> str | None:
    """`#rgb` / `#rrggbb` as an xcolor expression, `none` as None."""
    if value is None or value == "none":
        return None
    m = re.fullmatch(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})", value)
    if m is None:
        raise ConversionError(f"{source}: colour {value!r} is not #rgb, #rrggbb or none")
    h = m.group(1) if len(m.group(1)) == 6 else "".join(c * 2 for c in m.group(1))
    r, g, b = (int(h[i : i + 2], 16) for i in (0, 2, 4))
    return f"{{rgb,255:red,{r};green,{g};blue,{b}}}"


def _paint(el: ET.Element, source: str, *, fill_default: str | None) -> str:
    """TikZ path options for SVG fill and stroke (SVG defaults: fill black, stroke none, width 1)."""
    opts: list[str] = []
    fill = _colour(el.get("fill", fill_default), source)
    stroke = _colour(el.get("stroke"), source)
    if fill is not None:
        opts.append(f"fill={fill}")
    if stroke is not None:
        width = _num(el, "stroke-width", source) if el.get("stroke-width") is not None else "1"
        opts += [f"draw={stroke}", f"line width={width}pt"]
    return f"\\path[{','.join(opts)}]" if opts else "\\path"


def _tex_text(value: str) -> str:
    """SVG text as LaTeX, escaped as the tables escape theirs (`−`, `τ`, `≥` and the specials)."""
    return tex_escape(" ".join(value.split()))


def _points(value: str | None, source: str) -> list[tuple[str, str]]:
    nums = (value or "").replace(",", " ").split()
    if len(nums) < 2 or len(nums) % 2 or not all(NUM.match(n) for n in nums):
        raise ConversionError(f"{source}: points={value!r} is not a list of x,y pairs")
    return list(zip(nums[::2], nums[1::2], strict=True))


def _path_d(value: str | None, source: str) -> str:
    """Absolute M / L / Z only, the subset a polyline-like path needs."""
    d = value or ""
    token = r"[A-Za-z]|-?(?:\d+(?:\.\d*)?|\.\d+)"
    if not re.fullmatch(rf"(?:[\s,]*(?:{token}))*[\s,]*", d):
        raise ConversionError(f"{source}: path d={d!r} is not a list of commands and numbers")
    tokens = re.findall(token, d)
    out: list[str] = []
    i = 0
    while i < len(tokens):
        cmd, args = tokens[i], tokens[i + 1 : i + 3]
        if cmd == "Z" and out:
            out.append("-- cycle")
            i += 1
        elif cmd in ("M", "L") and len(args) == 2 and all(NUM.match(t) for t in args):
            out.append(("" if cmd == "M" else "-- ") + f"({args[0]},{args[1]})")
            i += 3
        else:
            raise ConversionError(f"{source}: path d={d!r}: only absolute M x y, L x y and Z are supported")
    if not out or not out[0].startswith("("):
        raise ConversionError(f"{source}: path d={d!r} must start with M")
    return " ".join(out)


def _element(el: ET.Element, source: str) -> str:
    tag = _tag(el)
    if not el.tag.startswith(SVG_NS) or tag not in ALLOWED:
        raise ConversionError(f"{source}: element <{el.tag}> is not one the converter draws")
    extra = sorted(set(el.attrib) - ALLOWED[tag])
    if extra:
        raise ConversionError(f"{source}: <{tag}> attribute(s) {', '.join(extra)} not supported")
    if len(el):
        raise ConversionError(f"{source}: <{tag}> has child elements")
    if tag != "text" and tag != "title" and (el.text or "").strip():
        raise ConversionError(f"{source}: <{tag}> has text content")
    if tag == "rect":
        x, y, w, h = (_num(el, a, source) for a in ("x", "y", "width", "height"))
        return f"{_paint(el, source, fill_default='#000')} ({x},{y}) rectangle ++({w},{h});"
    if tag == "circle":
        cx, cy, r = (_num(el, a, source) for a in ("cx", "cy", "r"))
        return f"{_paint(el, source, fill_default='#000')} ({cx},{cy}) circle[radius={r}pt];"
    if tag == "line":
        x1, y1, x2, y2 = (_num(el, a, source) for a in ("x1", "y1", "x2", "y2"))
        return f"{_paint(el, source, fill_default=None)} ({x1},{y1}) -- ({x2},{y2});"
    if tag in ("polyline", "path"):
        if el.get("fill") != "none":
            raise ConversionError(f"{source}: a filled <{tag}> is not supported (fill must be none)")
        if tag == "polyline":
            body = " -- ".join(f"({x},{y})" for x, y in _points(el.get("points"), source))
        else:
            body = _path_d(el.get("d"), source)
        return f"{_paint(el, source, fill_default=None)} {body};"
    if tag == "title":
        return ""
    x, y = _num(el, "x", source), _num(el, "y", source)
    anchor = el.get("text-anchor", "start")
    if anchor not in ANCHORS:
        raise ConversionError(f"{source}: text-anchor={anchor!r}")
    opts = [f"anchor={ANCHORS[anchor]}", "inner sep=0pt", "outer sep=0pt"]
    colour = _colour(el.get("fill"), source)
    if colour is not None:
        opts.append(f"text={colour}")
    transform = el.get("transform")
    if transform is not None:
        m = ROTATE.match(transform)
        if (
            m is None
            or not NUM.match(m.group(1))
            or (m.group(2) is not None and (m.group(2), m.group(3)) != (x, y))
        ):
            raise ConversionError(
                f"{source}: transform={transform!r}: only rotate(a) about the text's own x y"
            )
        angle = Decimal(m.group(1))
        opts.append(f"rotate={format(-angle, 'f') if angle else '0'}")  # SVG y points down: angle flips
    return f"\\node[{','.join(opts)}] at ({x},{y}) {{{_tex_text(el.text or '')}}};"


def svg_to_tikz(text: str, source: str) -> str:
    """One `tikzpicture` that draws the SVG with 1 px = 1 pt (scaled later as a whole), clipped
    to the viewBox as an SVG viewer clips it; painter's order is the SVG's element order."""
    try:
        root = ET.fromstring(text)
    except ET.ParseError as e:
        raise ConversionError(f"{source}: not well-formed XML ({e})") from None
    if root.tag != f"{SVG_NS}svg":
        raise ConversionError(f"{source}: root element is {root.tag!r}, not svg")
    extra = sorted(set(root.attrib) - {"width", "height", "viewBox", "font-family", "font-size"})
    if extra:
        raise ConversionError(f"{source}: <svg> attribute(s) {', '.join(extra)} not supported")
    width, height = _num(root, "width", source), _num(root, "height", source)
    if root.get("viewBox") != f"0 0 {width} {height}":
        raise ConversionError(f"{source}: viewBox {root.get('viewBox')!r} is not 0 0 width height")
    family = FAMILIES.get(root.get("font-family", "sans-serif"))
    if family is None:
        raise ConversionError(f"{source}: font-family {root.get('font-family')!r} not supported")
    size = _num(root, "font-size", source) if root.get("font-size") is not None else "16"
    title = next((" ".join((c.text or "").split()) for c in root if _tag(c) == "title"), "")
    font = f"{family}\\fontsize{{{size}}}{{{Decimal(size) * Decimal('1.2')}}}\\selectfont"
    lines = [
        f"% {source}: {title}".rstrip(),
        f"\\begin{{tikzpicture}}[x=1pt,y=-1pt,font={{{font}}}]",
        f"\\clip (0,0) rectangle ({width},{height});",
    ]
    lines += [s for s in (_element(el, source) for el in root) if s]
    lines.append("\\end{tikzpicture}")
    return "\n".join(lines)


def figure_tex(panels: Sequence[tuple[str, str]]) -> str:
    """A figure file: `\\vtfigpanels{n}`, then `\\vtfigpanel{<tikzpicture>}` per (name, svg text)
    in name order; paper/preamble.tex lays the panels out."""
    sources = ", ".join(f"bench/results/figures/{name}" for name, _ in panels)
    out = [
        HEADER.rstrip("\n").replace("from bench/results", f"from {sources}"),
        f"\\vtfigpanels{{{len(panels)}}}%",
    ]
    out += [f"\\vtfigpanel{{%\n{svg_to_tikz(svg, name)}}}%" for name, svg in panels]
    return "\n".join(out) + "\n"


def group_figures(figures: Path) -> dict[str, list[Path]]:
    """Figure name -> its panel SVGs (sorted). A figure is named by its CSV (`<name>.csv`, R-17);
    `<name>-<panel>.svg` is one of its panels and `<name>.svg` its only one. An SVG with no CSV
    (a placeholder figure) is its own one-panel figure."""
    if not figures.is_dir():
        return {}
    names = sorted(p.stem for p in figures.glob("*.csv"))
    out: dict[str, list[Path]] = {}
    for svg in sorted(figures.glob("*.svg"), key=lambda p: p.name):
        owners = [n for n in names if svg.stem == n or svg.stem.startswith(n + "-")]
        owner = max(owners, key=len) if owners else svg.stem
        out.setdefault(owner, []).append(svg)
    for name, svgs in out.items():
        if len(svgs) > 1 and any(s.stem == name for s in svgs):
            raise ConversionError(f"{name}: both {name}.svg and panel SVGs exist")
    return dict(sorted(out.items()))


