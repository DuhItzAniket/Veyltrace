"""Keep tool-specific agent files in sync with the canonical ones.

What it does
  1. Copies every shared skill from .agents/skills/<name>/ (Agent Skills format,
     the source of truth) to .claude/skills/<name>/ (the path Claude Code reads),
     and writes .claude/skills/README.md saying the folder is generated.
  2. Verifies that every directory below the repo root that has an AGENTS.md also
     has a CLAUDE.md whose content is exactly "@AGENTS.md\\n" (Claude Code does not
     read nested AGENTS.md files once a root CLAUDE.md exists). In sync mode a
     missing CLAUDE.md is created; a CLAUDE.md with other content is reported.
  3. Fails if duplicated instruction files exist (GEMINI.md, AGENTS.override.md,
     .cursor/rules/, .windsurf/rules/, .devin/rules/, .agents/rules/,
     .github/copilot-instructions.md, .github/instructions/). AGENTS.md is the
     only rules file; see docs/09-ai-agent-playbook.md section 1.
  4. Checks each SKILL.md has frontmatter with exactly `name` and `description`,
     and that `name` equals the folder name.
  5. Checks instruction size budgets: any AGENTS.md <= 12,000 characters
     (Windsurf/Devin per-rule-file limit) and root + nested AGENTS.md chain
     <= 32 KiB (Codex combined default).

Usage
  uv run python scripts/sync_agent_files.py           # write .claude/skills, create missing nested CLAUDE.md
  uv run python scripts/sync_agent_files.py --check   # CI: exit 1 if anything is out of sync, write nothing

Exit codes: 0 in sync, 1 out of sync or a rule violated, 2 usage error.
Standard library only; runs on Windows, macOS and Linux.
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".agents" / "skills"
DST = ROOT / ".claude" / "skills"
DST_README = "README.md"
CLAUDE_IMPORT = "@AGENTS.md\n"

# Directories never scanned (vendored, generated, archived or other worktrees).
PRUNE = {
    ".git", "node_modules", ".venv", "venv", "__pycache__", ".pytest_cache",
    ".ruff_cache", ".mypy_cache", ".hypothesis", "dist", "build", "_hackday-v1",
}
PRUNE_PATHS = {Path(".claude") / "worktrees"}

# Instruction files that would duplicate or override AGENTS.md.
FORBIDDEN_FILES = {"GEMINI.md", "AGENTS.override.md"}
FORBIDDEN_DIRS = [
    Path(".cursor") / "rules",
    Path(".windsurf") / "rules",
    Path(".devin") / "rules",
    Path(".agents") / "rules",
    Path(".github") / "instructions",
]
FORBIDDEN_ROOT_FILES = [Path(".github") / "copilot-instructions.md"]

MAX_AGENTS_CHARS = 12_000   # Windsurf/Devin workspace rule file limit
MAX_CHAIN_BYTES = 32 * 1024  # Codex project_doc_max_bytes default

TEXT_SUFFIXES = {".md", ".txt", ".py", ".sh", ".yaml", ".yml", ".json", ".toml", ".ps1"}

README_TEXT = """\
# .claude/skills (generated)

GENERATED by `scripts/sync_agent_files.py` from `.agents/skills/`. Do not edit files here.

Edit the skill under `.agents/skills/<name>/SKILL.md`, then run:

    uv run python scripts/sync_agent_files.py

CI runs the same script with `--check` and fails if this folder is out of date.
Why a copy and not a symlink: Git for Windows disables symlinks by default, and
Claude Code reads project skills from `.claude/skills/`. See docs/09-ai-agent-playbook.md section 6.
"""


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def read_normalised(p: Path) -> bytes:
    data = p.read_bytes()
    if p.suffix.lower() in TEXT_SUFFIXES:
        data = data.replace(b"\r\n", b"\n")
    return data


def walk(top: Path):
    """Yield (dirpath, filenames) under `top`, skipping pruned directories, sorted."""
    for dirpath, dirnames, filenames in os.walk(top):
        d = Path(dirpath)
        keep = []
        for name in sorted(dirnames):
            if name in PRUNE:
                continue
            if (d / name).relative_to(ROOT) in PRUNE_PATHS:
                continue
            keep.append(name)
        dirnames[:] = keep
        yield d, sorted(filenames)


# ---------------------------------------------------------------- skills

def expected_skill_files() -> dict[str, bytes]:
    """Map of path relative to DST -> content, as the sync would write it."""
    out: dict[str, bytes] = {DST_README: README_TEXT.encode("utf-8")}
    if not SRC.is_dir():
        return out
    for d, files in walk(SRC):
        for f in files:
            src = d / f
            out[(src.relative_to(SRC)).as_posix()] = read_normalised(src)
    return out


def actual_skill_files() -> dict[str, bytes]:
    out: dict[str, bytes] = {}
    if not DST.is_dir():
        return out
    for d, files in walk(DST):
        for f in files:
            p = d / f
            out[(p.relative_to(DST)).as_posix()] = read_normalised(p)
    return out


def sync_skills(check: bool) -> list[str]:
    want = expected_skill_files()
    have = actual_skill_files()
    problems: list[str] = []
    for path in sorted(set(want) | set(have)):
        if path not in have:
            problems.append(f"missing  .claude/skills/{path}")
        elif path not in want:
            problems.append(f"extra    .claude/skills/{path}")
        elif want[path] != have[path]:
            problems.append(f"differs  .claude/skills/{path}")
    if check or not problems:
        return problems
    # Write mode: rebuild DST exactly.
    for path in sorted(set(have) - set(want)):
        (DST / path).unlink()
    for path, data in sorted(want.items()):
        target = DST / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    # Remove directories left empty by deletions.
    for dirpath, dirnames, filenames in sorted(os.walk(DST), key=lambda t: -len(t[0])):
        if not dirnames and not filenames and Path(dirpath) != DST:
            Path(dirpath).rmdir()
    for p in problems:
        print(f"synced: {p}")
    return []


def validate_skill_frontmatter() -> list[str]:
    problems: list[str] = []
    if not SRC.is_dir():
        return problems
    for skill_dir in sorted(p for p in SRC.iterdir() if p.is_dir()):
        skill = skill_dir / "SKILL.md"
        if not skill.is_file():
            problems.append(f"{rel(skill_dir)}: no SKILL.md")
            continue
        lines = skill.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")
        if not lines or lines[0].strip() != "---":
            problems.append(f"{rel(skill)}: must start with '---' frontmatter")
            continue
        try:
            end = lines.index("---", 1)
        except ValueError:
            problems.append(f"{rel(skill)}: frontmatter not closed with '---'")
            continue
        keys: dict[str, str] = {}
        for line in lines[1:end]:
            if not line.strip() or line.startswith((" ", "\t")):
                continue
            key, _, value = line.partition(":")
            keys[key.strip()] = value.strip().strip("\"'")
        if set(keys) != {"name", "description"}:
            problems.append(f"{rel(skill)}: frontmatter keys must be exactly name, description (found {sorted(keys)})")
        if keys.get("name") != skill_dir.name:
            problems.append(f"{rel(skill)}: name '{keys.get('name')}' must equal folder name '{skill_dir.name}'")
        if not keys.get("description"):
            problems.append(f"{rel(skill)}: description is empty")
    return problems


# ---------------------------------------------------------------- instruction files

def check_instruction_files(check: bool) -> list[str]:
    problems: list[str] = []
    agents_files: list[Path] = []
    for d, files in walk(ROOT):
        if "AGENTS.md" in files:
            agents_files.append(d / "AGENTS.md")
        for name in FORBIDDEN_FILES & set(files):
            problems.append(f"forbidden instruction file: {rel(d / name)} (AGENTS.md is the only rules file)")
    for fd in FORBIDDEN_DIRS:
        if (ROOT / fd).is_dir() and any((ROOT / fd).iterdir()):
            problems.append(f"forbidden instruction folder: {fd.as_posix()}/ (AGENTS.md is the only rules file)")
    for ff in FORBIDDEN_ROOT_FILES:
        if (ROOT / ff).is_file():
            problems.append(f"forbidden instruction file: {ff.as_posix()} (needs an ADR and an allow-list change in this script)")

    root_agents = ROOT / "AGENTS.md"
    root_claude = ROOT / "CLAUDE.md"
    if not root_agents.is_file():
        problems.append("AGENTS.md missing at repo root")
    if not root_claude.is_file():
        problems.append("CLAUDE.md missing at repo root (must contain the line @AGENTS.md)")
    elif "@AGENTS.md" not in root_claude.read_text(encoding="utf-8").splitlines():
        problems.append("CLAUDE.md at repo root must contain the import line @AGENTS.md")

    root_bytes = len(root_agents.read_bytes()) if root_agents.is_file() else 0
    for agents in agents_files:
        text = agents.read_text(encoding="utf-8")
        if len(text) > MAX_AGENTS_CHARS:
            problems.append(f"{rel(agents)}: {len(text)} characters > {MAX_AGENTS_CHARS} (Windsurf/Devin rule-file limit); move detail to docs/")
        if agents == root_agents:
            continue
        chain = root_bytes + len(agents.read_bytes())
        if chain > MAX_CHAIN_BYTES:
            problems.append(f"{rel(agents)}: root + nested AGENTS.md = {chain} bytes > {MAX_CHAIN_BYTES} (Codex combined cap)")
        claude = agents.parent / "CLAUDE.md"
        if not claude.is_file():
            if check:
                problems.append(f"missing {rel(claude)} (must contain exactly '@AGENTS.md' and a newline)")
            else:
                claude.write_bytes(CLAUDE_IMPORT.encode("utf-8"))
                print(f"created: {rel(claude)}")
        elif read_normalised(claude) != CLAUDE_IMPORT.encode("utf-8"):
            problems.append(f"{rel(claude)}: content must be exactly '@AGENTS.md' plus a newline")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify only; write nothing; exit 1 if out of sync")
    args = ap.parse_args()

    if not SRC.is_dir():
        print(f"note: {rel(SRC)}/ does not exist; nothing to copy")
    problems = validate_skill_frontmatter()
    problems += sync_skills(args.check)
    problems += check_instruction_files(args.check)

    if problems:
        print("FAIL: agent files out of sync or rule violated:")
        for p in problems:
            print(f"  {p}")
        if args.check:
            print("Fix: uv run python scripts/sync_agent_files.py  (then commit the result)")
        return 1
    print("OK: .claude/skills matches .agents/skills; nested CLAUDE.md files present; no duplicate rule files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
