TS_JSON_VALUE = "export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };"


def ts_type(t: T, used: set[str]) -> str:
    k = t.kind
    simple = {"str": "string", "int": "number", "float": "number", "bool": "boolean", "null": "null"}
    if k in simple:
        return simple[k]
    if k == "any":
        used.add("JsonValue")
        return "JsonValue"
    if k == "lit":
        return " | ".join(json.dumps(v) for v in t.args)
    if k == "list":
        inner = ts_type(t.args[0], used)
        return f"Array<{inner}>" if " " in inner else f"{inner}[]"
    if k == "tuple":
        return "[" + ", ".join(ts_type(a, used) for a in t.args) + "]"
    if k == "map":
        return f"Record<string, {ts_type(t.args[0], used)}>"
    if k == "union":  # int and float both render as number: keep one (no duplicate union members)
        return " | ".join(dict.fromkeys(ts_type(a, used) for a in t.args))
    return t.args[0]


def render_ts(b: Builder, intro: list[str], contract_names: list[str] | None) -> str:
    """`export type` per alias, `export interface` per class; nullable = `T | null`, ints = `number`."""
    used: set[str] = set()
    blocks: list[str] = []
    for n in ordered(b.named):
        safe = n.doc.replace("*/", "*\\/")
        doc = [f"/** {safe} */"] if n.doc else []
        if n.fields is None:
            blocks.append("\n".join([*doc, f"export type {n.name} = {ts_type(n.alias or T('any'), used)};"]))
        elif not n.fields:
            blocks.append("\n".join([*doc, f"export type {n.name} = Record<string, never>;"]))
        else:
            props = []
            for p in n.fields:
                key = p.json_name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", p.json_name) else json.dumps(p.json_name)
                props.append(f"  {key}{'?' if p.optional else ''}: {ts_type(p.type, used)};")
            blocks.append("\n".join([*doc, f"export interface {n.name} {{", *props, "}"]))
    if contract_names is not None:
        names = " | ".join(json.dumps(n) for n in contract_names) or "never"
        blocks.append(f"/** Names of all contracts (x-veyltrace.name). */\nexport type ContractName = {names};")
    if "JsonValue" in used:
        blocks.insert(0, TS_JSON_VALUE)
    return "\n".join([f"// {HEADER}", *(f"// {line}" for line in intro)]) + "\n\n" + "\n\n".join(blocks) + "\n"


