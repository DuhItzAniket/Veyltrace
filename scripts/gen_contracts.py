def model_block(n: Named, used: set[str]) -> str:
    """A pydantic class, or a module-level alias with a `#:` doc comment."""
    if n.fields is None:
        assert n.alias is not None
        doc = [f"#: {line}" for line in textwrap.wrap(n.doc, WIDTH - 3, break_long_words=False)]
        prefix = f"{n.name} = "
        return "\n".join([*doc, prefix + render(py_doc(n.alias, used), 0, len(prefix))])
    used.update(("BaseModel", "ConfigDict"))
    lines = [
        f"class {n.name}(BaseModel):",
        docstring(n.doc, 4),
        "",
        '    model_config = ConfigDict(extra="forbid", frozen=True)',
    ]
    seen: set[str] = set()
    for p in n.fields:
        name, aliased = py_ident(p.json_name)
        if name in seen:
            raise GenError(f"{n.origin}: two properties map to the Python name {name!r}")
        seen.add(name)
        d = py_doc(p.type, used)
        if aliased:
            used.update(("Annotated", "Field"))
            d = G("Annotated[", (d, f"Field(alias={py_str(p.json_name)})"), "]")
        if len(lines) == 4:
            lines.append("")
        lines.append(f"    {name}: " + render(d, 4, len(name) + 6))
    return "\n".join(lines)


def render_models(b: Builder) -> str:
    used: set[str] = set()
    blocks = [(n.fields is not None, model_block(n, used)) for n in ordered(b.named)]
    imports = [
        import_line("typing", used & {"Annotated", "Literal"}),
        import_line("pydantic", used & {"BaseModel", "ConfigDict", "Field", "JsonValue", "StringConstraints"}),
    ]
    head = [
        f"# {HEADER}",
        '"""Pydantic v2 models of the Veyltrace data contracts (one class per object, Literal per vocabulary)."""',
        *(line for group in imports if group for line in ["", *group]),
        "",
        "__all__ = " + render(G("[", tuple(py_str(n) for n in sorted(b.named, key=all_key)), "]"), 0, 10),
    ]
    return "\n".join(head) + "\n\n\n" + join_blocks(blocks) + "\n"


def arrow_type(xa: str) -> str | G:
    if xa == "list<string>":  # items are non-null strings, as the schema says
        return G("pa.list_(", (G("pa.field(", ('"item"', "pa.string()", "nullable=False"), ")"),), ")")
    return ARROW[xa][1]


def render_arrow(contracts: list[SchemaFile], files: dict[str, SchemaFile]) -> str:
    blocks: list[tuple[bool, str]] = []
    names: list[str] = []
    for sf in contracts:
        if sf.kind not in TABLE_KINDS:
            continue
        fields = []
        for col, ps in sf.data.get("properties", {}).items():
            xa = ps.get("x-arrow") if isinstance(ps, dict) else None
            if xa not in ARROW:
                raise GenError(f"{sf.file}: column {col!r} has no valid x-arrow")
            nullable = strip_null(files, sf, ps, sf.file)[2]
            fields.append(G("pa.field(", (py_str(col), arrow_type(xa), f"nullable={nullable}"), ")"))
        meta = sf.meta or {}
        md = f'metadata={{b"veyltrace.schema": b"{sf.stem}/{meta.get("version")}"}}'
        prefix = f"{const_name(sf.stem)} = "
        blocks.append((False, prefix + render(G("pa.schema(", (G("[", tuple(fields), "]"), md), ")"), 0, len(prefix))))
        names.append(sf.stem)
    mapping = G("MappingProxyType(", (G("{", tuple(f"{py_str(n)}: {const_name(n)}" for n in names), "}"),), ")")
    prefix = "SCHEMAS: Mapping[str, pa.Schema] = "
    blocks.append((False, prefix + render(mapping, 0, len(prefix))))
    head = [
        f"# {HEADER}",
        '"""pyarrow schemas of the table contracts (Parquet, CSV); column order = schema property order."""',
        "",
        "from collections.abc import Mapping",
        "from types import MappingProxyType",
        "",
        "import pyarrow as pa",
    ]
    return "\n".join(head) + "\n\n" + join_blocks(blocks) + "\n"


