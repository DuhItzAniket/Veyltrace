@dataclass(frozen=True)
class G:
    """A bracketed group: flat if it fits in WIDTH, else one item per line with a magic trailing comma."""

    open: str
    items: tuple[Any, ...]  # str | G
    close: str
    tuple1: bool = False  # a one-element tuple keeps its comma when flat


@dataclass(frozen=True)
class U:
    """A union `A | B`: ruff wraps a too-long one in parentheses, then breaks before each `|`."""

    items: tuple[Any, ...]  # str | G


def flat(d: str | G | U) -> str:
    if isinstance(d, str):
        return d
    if isinstance(d, U):
        return " | ".join(flat(i) for i in d.items)
    one = "," if d.tuple1 and len(d.items) == 1 else ""
    return d.open + ", ".join(flat(i) for i in d.items) + one + d.close


def render(d: str | G | U, indent: int, used: int, tail: int = 0) -> str:
    """Lay out `d` starting at column `used` inside a block indented by `indent`."""
    f = flat(d)
    if isinstance(d, str) or used + len(f) + tail <= WIDTH or not d.items:
        return f
    if isinstance(d, U):
        pad = " " * (indent + 4)
        if indent + 4 + len(f) <= WIDTH:
            return f"(\n{pad}{f}\n{' ' * indent})"
        first = pad + render(d.items[0], indent + 4, indent + 4)
        rest = [pad + "| " + render(i, indent + 4, indent + 6) for i in d.items[1:]]
        return "\n".join(["(", first, *rest, " " * indent + ")"])
    pad, comma = " " * (indent + 4), "," if len(d.items) > 1 or d.tuple1 else ""
    body = [
        pad + render(flat(i) if isinstance(i, U) else i, indent + 4, indent + 4, len(comma)) + comma for i in d.items
    ]
    return "\n".join([d.open, *body, " " * indent + d.close])


def prefixed(prefix: str, d: str | G | U) -> str | G:
    if isinstance(d, U):
        d = flat(d)
    return prefix + d if isinstance(d, str) else G(prefix + d.open, d.items, d.close, d.tuple1)


def tuple_doc(items: list[str | G]) -> str | G:
    return G("(", tuple(items), ")", tuple1=True) if items else "()"


def docstring(text: str, indent: int) -> str:
    pad = " " * indent
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    text = text[:-1] + '\\"' if text.endswith('"') else text
    if len(pad) + len(text) + 6 <= WIDTH:
        return f'{pad}"""{text}"""'
    lines = textwrap.wrap(text, WIDTH - indent - 3, break_long_words=False, break_on_hyphens=False)
    if len(lines) == 1:
        return f'{pad}"""{text}"""'
    return "\n".join([f'{pad}"""{lines[0]}', *(pad + line for line in lines[1:]), f'{pad}"""'])


def import_line(module: str, names: set[str]) -> list[str]:
    if not names:
        return []
    members = tuple(sorted(names, key=isort_key))
    line = f"from {module} import {', '.join(members)}"
    return [line if len(line) <= WIDTH else render(G(f"from {module} import (", members, ")"), 0, WIDTH)]


def join_blocks(blocks: list[tuple[bool, str]]) -> str:
    """Two blank lines around classes, one between plain assignments (ruff-format stable)."""
    out, prev_cls = [], True
    for is_cls, text in blocks:
        if out:
            out.append("\n\n\n" if is_cls or prev_cls else "\n\n")
        out.append(text)
        prev_cls = is_cls
    return "".join(out)


def py_doc(t: T, used: set[str], *, plain: bool = False) -> str | G | U:
    """Python annotation; `plain` = frozen-dataclass style (tuples, Mapping, no pydantic constraints)."""
    k = t.kind
    if k in ("str", "int", "float"):
        base = k
        if not t.cons or plain:
            return base
        used.add("Annotated")
        kw = tuple(f"{c}={py_pattern(v) if c == 'pattern' else py_lit(v)}" for c, v in t.cons)
        ctor = "StringConstraints" if k == "str" else "Field"
        used.add(ctor)
        return G("Annotated[", (base, G(f"{ctor}(", kw, ")")), "]")
    if k in ("bool", "null"):
        return "bool" if k == "bool" else "None"
    if k == "any":
        used.update(() if plain else ("JsonValue",))
        return "object" if plain else "JsonValue"
    if k == "lit":
        used.add("Literal")
        return G("Literal[", tuple(py_lit(v) for v in t.args), "]")
    if k == "list":
        inner = py_doc(t.args[0], used, plain=plain)
        if plain:
            return G("tuple[", (inner, "..."), "]")
        doc: str | G | U = G("list[", (inner,), "]")
        if t.cons:
            used.update(("Annotated", "Field"))
            doc = G("Annotated[", (doc, G("Field(", tuple(f"{c}={v!r}" for c, v in t.cons), ")")), "]")
        return doc
    if k == "tuple":
        return G("tuple[", tuple(py_doc(a, used, plain=plain) for a in t.args), "]")
    if k == "map":
        used.update(("Mapping",) if plain else ())
        return G("Mapping[" if plain else "dict[", ("str", py_doc(t.args[0], used, plain=plain)), "]")
    if k == "union":
        return U(tuple(py_doc(a, used, plain=plain) for a in t.args))
    return t.args[0]


