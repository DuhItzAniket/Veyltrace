TICK = re.compile(r"`([^`]+)`")
HEADING = re.compile(r"^#{1,6}\s+(.*)$")
EXT = re.compile(r"\.(json|jsonl|parquet|csv)$")
CONTRACT_TOKEN = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)*$")
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def section_fields(lines: list[str]) -> tuple[list[str], str]:
    """Top-level field names of one 03 section and where they came from (table, prose or json block)."""
    fields: list[str] = []
    tables: list[list[str]] = []
    in_table = False
    for line in lines:
        is_row = line.lstrip().startswith("|")
        if is_row and not in_table:
            tables.append([])
        if is_row:
            tables[-1].append(line)
        in_table = is_row
    for table in tables:
        cells = [re.split(r"(?<!\\)\|", row.strip().strip("|")) for row in table]
        if cells[0][0].strip() not in ("Field", "Column"):
            continue
        for row in cells[2:]:
            fields += [tok.strip().rstrip("?").split(".")[0] for tok in TICK.findall(row[0])]
    if fields:
        return list(dict.fromkeys(f for f in fields if IDENT.match(f))), "table"
    for line in lines:
        if "Columns:" in line:  # 03 §13.2 style: "Columns: `a`, `b` (note), …. Next sentence."
            tail = line.split("Columns:", 1)[1]
            while re.search(r"\([^()]*\)", tail):
                tail = re.sub(r"\([^()]*\)", "", tail)
            tail = re.split(r"\.(?:\s|$)", tail, maxsplit=1)[0]
            return list(dict.fromkeys(t for t in TICK.findall(tail) if IDENT.match(t))), "columns prose"
    text = "\n".join(lines)
    m = re.search(r"```json\n(.*?)```", text, re.DOTALL)
    if m:
        try:
            obj = json.loads(m.group(1))
            return (list(obj) if isinstance(obj, dict) else []), "json block"
        except ValueError:
            pass
    return [], "none"


def parse_03(text: str, names: set[str]) -> dict[str, tuple[list[str], str]]:
    """Map contract name -> (top-level fields, source) for every 03 heading that names a contract."""
    sections: dict[str, list[str]] = {}
    current, in_code = None, False
    for line in text.splitlines():
        if line.startswith("```"):
            in_code = not in_code
        m = None if in_code else HEADING.match(line)
        if m:
            toks = [EXT.sub("", t.strip()) for t in TICK.findall(m.group(1))]
            known = [t for t in toks if t in names]
            current = known[0] if known else toks[0] if toks and CONTRACT_TOKEN.match(toks[0]) else None
            if current:
                sections.setdefault(current, [])
            continue
        if current:
            sections[current].append(line)
    return {k: section_fields(v) for k, v in sections.items()}


def parity(inputs: Inputs, report: Report) -> bool:
    """Print the 03 field-parity report; return True on any drift."""
    path = inputs.root / "docs" / "03-contracts.md"
    if not path.is_file():
        report.warn("docs/03-contracts.md not found; parity check skipped")
        return False
    contracts = {sf.stem: sf for sf in inputs.contracts}
    doc = parse_03(path.read_bytes().decode("utf-8"), set(contracts))
    print("03 parity (docs/03-contracts.md top-level fields vs schema properties):")
    drift = False
    for name in sorted(set(doc) | set(contracts)):
        if name not in contracts:
            print(f"  {name}: 03 section has no schema")
            drift = True
            continue
        if name not in doc:
            print(f"  {name}: no 03 section")
            drift = True
            continue
        fields, source = doc[name]
        props = list(contracts[name].data.get("properties") or {})
        if source == "none":
            print(f"  {name}: 03 section has no field table; not compared")
            continue
        only_doc = [f for f in fields if f not in props]
        only_schema = [p for p in props if p not in fields]
        parts = []
        if only_doc:
            parts.append(f"in 03, not in schema: {', '.join(only_doc)}")
        if only_schema:
            parts.append(f"in schema, not in 03: {', '.join(only_schema)}")
        drift |= bool(parts)
        print(f"  {name}: " + ("; ".join(parts) if parts else f"ok ({len(props)} fields, from {source})"))
    return drift


