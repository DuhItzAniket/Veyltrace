def same(a: Any, b: Any) -> bool:
    """JSON equality that also tells 3 from 3.0 and 1 from true: canonical_json renders them
    differently, so a model that turns an int into a float changes every hash over it."""
    if type(a) is not type(b):
        return False
    if isinstance(a, dict):
        return a.keys() == b.keys() and all(same(a[k], b[k]) for k in a)
    if isinstance(a, list):
        return len(a) == len(b) and all(same(x, y) for x, y in zip(a, b, strict=True))
    return bool(a == b)


def first_diff(a: Any, b: Any, path: str = "$") -> str:
    if isinstance(a, dict) and isinstance(b, dict):
        for k in sorted(set(a) | set(b)):
            if k not in a or k not in b:
                return f"{path}.{k} present on one side only"
            if not same(a[k], b[k]):
                return first_diff(a[k], b[k], f"{path}.{k}")
    if isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        for i, (x, y) in enumerate(zip(a, b, strict=True)):
            if not same(x, y):
                return first_diff(x, y, f"{path}[{i}]")
    return f"{path}: {a!r} != {b!r}"


def roundtrip(python_dir: Path, inputs: Inputs, report: Report) -> None:
    """Import the freshly generated package and round-trip every example through its model."""
    import pyarrow as pa
    from pydantic import ValidationError

    sys.dont_write_bytecode = True
    for mod in [m for m in sys.modules if m == PKG or m.startswith(PKG + ".")]:
        del sys.modules[mod]
    sys.path.insert(0, str(python_dir))
    importlib.invalidate_caches()
    try:
        importlib.import_module(PKG)
        registry = importlib.import_module(f"{PKG}.registry")
        predicates = importlib.import_module(f"{PKG}.predicates")
    except Exception as exc:  # noqa: BLE001 - any failure of the generated code is the finding
        report.error(f"generated package does not import: {exc!r}")
        return
    finally:
        sys.path.remove(str(python_dir))
    if not Path(registry.__file__ or "").resolve().is_relative_to(python_dir.resolve()):
        report.error(f"imported a stale {PKG} from {registry.__file__}")
        return
    for sf in inputs.schemas.values():
        if registry.schema_json(sf.stem) != sf.data:
            report.error(f"packaged copy of {sf.file} does not load back equal")
    for name, info in registry.CONTRACTS.items():
        schema = info.arrow_schema
        if info.kind in TABLE_KINDS and (
            not isinstance(schema, pa.Schema)
            or schema.metadata != {b"veyltrace.schema": f"{name}/{info.version}".encode()}
        ):
            report.error(f"{name}: Arrow schema missing or without veyltrace.schema metadata")
        ex = example_of(inputs, inputs.schemas[f"{name}.schema.json"])[0]
        rows = [ex] if info.kind == "json" else ex
        if ex is None or ex is BROKEN or not isinstance(rows, list):
            continue
        for i, row in enumerate(rows):
            label = f"{name} example" + ("" if info.kind == "json" else f"[{i}]")
            try:
                dumped = info.model.model_validate(row).model_dump(mode="json", by_alias=True)
            except ValidationError as exc:
                e = exc.errors()[0]
                report.error(f"{label}: model rejects it at {'.'.join(map(str, e['loc']))}: {e['msg']}")
                continue
            if not same(dumped, row):
                report.error(f"{label}: model round-trip differs: {first_diff(row, dumped)}")
        if isinstance(schema, pa.Schema) and all(isinstance(r, dict) for r in rows):
            try:
                pa.Table.from_pylist(rows, schema=schema)
            except (pa.ArrowException, TypeError, ValueError, OverflowError) as exc:
                report.error(f"{name} example: rows do not fit the Arrow schema: {exc}")
    expected = inputs.predicates
    if expected is not None and expected is not BROKEN and inputs.schemas.get("predicates.schema.json"):
        entries = locate_predicates(inputs, inputs.schemas["predicates.schema.json"])[2]
        if len(predicates.PREDICATES) != len(entries):
            report.error(f"predicates.py holds {len(predicates.PREDICATES)} predicates, predicates.json {len(entries)}")


