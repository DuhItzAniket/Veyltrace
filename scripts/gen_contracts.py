SCOPES = ("python", "ts")  # the only subtrees of contracts/generated/ this script owns


def existing(out: Path) -> dict[str, Path]:
    """Files of the owned subtrees, minus tool caches (dot-dirs, __pycache__, *.egg-info)."""
    found: dict[str, Path] = {}
    for scope in SCOPES:
        for p in sorted((out / scope).rglob("*")) if (out / scope).is_dir() else []:
            rel = p.relative_to(out)
            if p.is_file() and not any(
                x.startswith(".") or x == "__pycache__" or x.endswith(".egg-info") for x in rel.parts
            ):
                found[rel.as_posix()] = p
    return found


def write_tree(out: Path, files: dict[str, bytes]) -> int:
    """Write changed files, delete stale ones; returns the number of files touched."""
    touched = 0
    for rel, data in files.items():
        path = out / rel
        if not path.is_file() or path.read_bytes() != data:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            touched += 1
    for rel, path in existing(out).items():
        if rel not in files:
            path.unlink()
            touched += 1
    for scope in SCOPES:
        dirs = (
            sorted((p for p in (out / scope).rglob("*") if p.is_dir()), reverse=True) if (out / scope).is_dir() else []
        )
        for d in dirs:
            if not any(d.iterdir()):
                d.rmdir()
    return touched


def diff_tree(out: Path, files: dict[str, bytes]) -> tuple[list[str], list[str], list[str]]:
    """(missing from the committed tree, stale in it, different) relative to contracts/generated/."""
    have = existing(out)
    added = [r for r in files if r not in have]
    removed = [r for r in have if r not in files]
    changed = [r for r in files if r in have and have[r].read_bytes() != files[r]]
    return added, sorted(removed), changed


