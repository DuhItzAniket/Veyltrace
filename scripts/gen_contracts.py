@dataclass(frozen=True)
class T:
    """Type IR node; kind is str|int|float|bool|null|any|lit|list|tuple|map|union|ref."""

    kind: str
    args: tuple[Any, ...] = ()
    cons: tuple[tuple[str, Any], ...] = ()


@dataclass(frozen=True)
class Prop:
    json_name: str
    type: T
    optional: bool = False  # only in lenient (OpenAPI) mode; contract fields are always present


@dataclass
class Named:
    """A generated named type: a class (`fields` set) or a type alias (`alias` set)."""

    name: str
    origin: str
    doc: str
    fields: list[Prop] | None = None
    alias: T | None = None


def union(options: list[T]) -> T:
    """Flatten, dedupe and put null last."""
    out: list[T] = []
    for o in options:
        for x in o.args if o.kind == "union" else (o,):
            if x not in out:
                out.append(x)
    out.sort(key=lambda x: x.kind == "null")
    return out[0] if len(out) == 1 else T("union", tuple(out))


def cons_of(s: dict[str, Any], table: dict[str, str]) -> tuple[tuple[str, Any], ...]:
    return tuple((py, s[js]) for js, py in table.items() if js in s and not (py == "min_length" and s[js] == 0))


def is_class(s: Any) -> bool:
    """An object with declared properties (or explicitly none), as opposed to a free-key map."""
    return (
        isinstance(s, dict)
        and "$ref" not in s
        and s.get("type") in ("object", None)
        and ("properties" in s or s.get("additionalProperties") is False)
    )


JSON_TYPES = frozenset({"null", "boolean", "integer", "number", "string", "array", "object"})


def is_json_any(s: Any, ptr: str) -> bool:
    """A def spelling "any JSON value" recursively (config_lock JsonValue): it maps to JsonValue."""
    opts = s.get("anyOf") if isinstance(s, dict) else None
    if not isinstance(opts, list) or {o.get("type") for o in opts if isinstance(o, dict)} != JSON_TYPES:
        return False
    inner = [o.get("items", o.get("additionalProperties")) for o in opts if o.get("type") in ("array", "object")]
    return all(i in ({}, True, {"$ref": ptr}) for i in inner)


class Builder:
    """Translates schemas into named types. `lenient` is for OpenAPI; `inline` inlines non-object defs."""

    def __init__(self, files: dict[str, SchemaFile], *, lenient: bool = False, inline: bool = False) -> None:
        self.files, self.lenient, self.inline = files, lenient, inline
        self.named: dict[str, Named] = {}
        self.by_origin: dict[str, str] = {}
        self.busy: set[str] = set()
        self.notes: list[str] = []  # schema titles that disagree with the generated class name

    def claim(self, name: str, origin: str, doc: str, **kw: Any) -> Named:
        if name in RESERVED or not name.isidentifier():
            raise GenError(f"{origin}: generated name {name!r} is reserved or not an identifier")
        other = self.named.get(name)
        if other is not None and other.origin != origin:
            raise GenError(f"name collision: {name!r} from {other.origin} and {origin}; rename one")
        self.named[name] = n = Named(name, origin, doc, **kw)
        self.by_origin[origin] = name
        return n

    def root(self, sf: SchemaFile) -> T:
        origin = f"{sf.file}#"
        if origin in self.by_origin:
            return T("ref", (self.by_origin[origin],))
        return self.ir(sf.data, sf, "#", sf.title_name)

    def define(self, sf: SchemaFile, defname: str) -> T:
        """Type of a $defs entry: a class or alias named PascalCase(def name)."""
        ptr = "#/" + "/".join(sf.defs_path) + "/" + defname
        origin = sf.file + ptr
        if origin in self.by_origin:
            return T("ref", (self.by_origin[origin],))
        schema, name = sf.defs[defname], pascal(defname)
        if is_json_any(schema, ptr):
            return T("any")
        if origin in self.busy:
            raise GenError(f"{origin}: recursive schemas are not supported (except the JSON-value shape)")
        self.busy.add(origin)
        try:
            t = self.ir(schema, sf, ptr, name if is_class(schema) else name + "Item")
        finally:
            self.busy.discard(origin)
        if is_class(schema) or self.inline:
            return t
        self.claim(name, origin, one_line(schema.get("description")) if isinstance(schema, dict) else "", alias=t)
        return T("ref", (name,))

    def check_keys(self, s: dict[str, Any], where: str) -> None:
        for k, v in s.items():
            if k.startswith("x-") or k in ANNOTATION_KEYS or k in SHAPE_KEYS or k in VALIDATION_ONLY or self.lenient:
                continue
            if k == "allOf" and all(isinstance(m, dict) and set(m) <= CONDITIONAL_KEYS for m in v):
                continue  # if/then/else conditionals only; they constrain values, not shape
            raise GenError(f"{where}: unsupported keyword {k!r} (extend gen_contracts.py and CONVENTIONS.md first)")

    def ir(self, s: Any, sf: SchemaFile, ptr: str, hint: str) -> T:
        """Type IR of schema `s` at `ptr`; `hint` names an inline object found here."""
        where = f"{sf.file}{ptr}"
        if s is True or s == {}:
            return T("any")
        if not isinstance(s, dict):
            raise GenError(f"{where}: schema must be an object or true")
        self.check_keys(s, where)
        if "$ref" in s:
            target, defname = resolve_ref(self.files, sf, s["$ref"], where)
            if defname is not None:
                return self.define(target, defname)
            if not target.is_contract:
                raise GenError(f"{where}: $ref to the whole non-contract schema {target.file}")
            return self.root(target)
        if "const" in s:
            return T("lit", (s["const"],))
        if isinstance(s.get("enum"), list):
            vals = s["enum"]
            lit = T("lit", tuple(v for v in vals if v is not None))
            return union([lit, T("null")]) if None in vals else lit
        for key in ("anyOf", "oneOf"):
            if isinstance(s.get(key), list):
                return union([self.ir(b, sf, f"{ptr}/{key}/{i}", hint) for i, b in enumerate(s[key])])
        typ = s.get("type")
        if typ is None and ("properties" in s or (self.lenient and "additionalProperties" in s)):
            typ = "object"
        if typ is None:
            if all(k in ANNOTATION_KEYS or k in VALIDATION_ONLY or k == "allOf" or k.startswith("x-") for k in s):
                return T("any")  # e.g. {"description": ...}: any JSON value
            raise GenError(f"{where}: schema has no type")
        if isinstance(typ, list):
            return union([self.ir({**s, "type": t}, sf, ptr, hint) for t in typ])
        if typ == "string":
            return T("str", (), cons_of(s, STR_CONS))
        if typ in ("integer", "number"):
            return T("int" if typ == "integer" else "float", (), cons_of(s, NUM_CONS))
        if typ in ("boolean", "null"):
            return T("bool" if typ == "boolean" else "null")
        if typ == "array":
            return self.array(s, sf, ptr, hint)
        if typ == "object":
            return self.obj(s, sf, ptr, hint)
        raise GenError(f"{where}: unsupported type {typ!r}")

    def array(self, s: dict[str, Any], sf: SchemaFile, ptr: str, hint: str) -> T:
        if "prefixItems" in s:
            items = s["prefixItems"]
            if not self.lenient and not (
                s.get("items") is False or s.get("minItems") == s.get("maxItems") == len(items)
            ):
                raise GenError(f"{sf.file}{ptr}: tuples need minItems == maxItems == len(prefixItems)")
            return T(
                "tuple", tuple(self.ir(b, sf, f"{ptr}/prefixItems/{i}", f"{hint}Item{i}") for i, b in enumerate(items))
            )
        return T("list", (self.ir(s.get("items", True), sf, f"{ptr}/items", hint),), cons_of(s, ARR_CONS))

    def obj(self, s: dict[str, Any], sf: SchemaFile, ptr: str, hint: str) -> T:
        if is_class(s):
            origin = sf.file + ptr
            if origin in self.by_origin:
                return T("ref", (self.by_origin[origin],))
            fields: list[Prop] = []
            self.claim(hint, origin, one_line(s.get("description")) or f"`{sf.stem}` {ptr}.", fields=fields)
            if ptr != "#" and isinstance(s.get("title"), str) and s["title"] != hint:
                self.notes.append(f"{origin}: title {s['title']!r} is ignored; the class is {hint} (R-01 naming rule)")
            required = set(s.get("required", ()))
            for k, v in (s.get("properties") or {}).items():
                t = self.ir(v, sf, f"{ptr}/properties/{k}", hint + pascal(k))
                fields.append(Prop(k, t, self.lenient and k not in required))
            return T("ref", (hint,))
        ap = s.get("additionalProperties", True)
        if ap is True and not self.lenient:
            raise GenError(
                f"{sf.file}{ptr}: object needs properties or an additionalProperties schema (CONVENTIONS §3.3)"
            )
        return T("map", (self.ir(ap, sf, f"{ptr}/additionalProperties", hint + "Value"),))


def refs(t: T) -> set[str]:
    if t.kind == "ref":
        return {t.args[0]}
    if t.kind in ("list", "tuple", "map", "union"):
        return set().union(*(refs(a) for a in t.args))
    return set()


def ordered(named: dict[str, Named]) -> list[Named]:
    """Dependency-first; among ready types aliases before classes, then alphabetical (Kahn + heap)."""
    deps: dict[str, set[str]] = {}
    for n in named.values():
        types = [p.type for p in n.fields] if n.fields is not None else [n.alias] if n.alias else []
        deps[n.name] = set().union(*(refs(t) for t in types)) & named.keys()
    users: dict[str, set[str]] = {k: set() for k in named}
    for k, ds in deps.items():
        for d in ds:
            users[d].add(k)
    heap = [(named[k].fields is not None, k) for k, ds in deps.items() if not ds]
    heapq.heapify(heap)
    out: list[Named] = []
    while heap:
        _, k = heapq.heappop(heap)
        out.append(named[k])
        for u in sorted(users[k]):
            deps[u].discard(k)
            if not deps[u]:
                heapq.heappush(heap, (named[u].fields is not None, u))
    if len(out) != len(named):
        raise GenError("dependency cycle among: " + ", ".join(sorted(set(named) - {n.name for n in out})))
    return out


