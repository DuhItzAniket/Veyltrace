class GenError(Exception):
    """A schema construct the generator cannot translate; nothing is written."""


class Report:
    """Collects errors and warnings and prints each one as it arrives."""

    def __init__(self) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []

    def error(self, msg: str) -> None:
        self.errors.append(msg)
        print(f"ERROR {msg}")

    def warn(self, msg: str) -> None:
        self.warnings.append(msg)
        print(f"WARN  {msg}")


# --------------------------------------------------------------------------- inputs


@dataclass
class SchemaFile:
    """One schema document; `defs_path` is ("components", "schemas") for the OpenAPI pseudo-file."""

    file: str
    data: dict[str, Any]
    raw: bytes
    defs_path: tuple[str, ...] = ("$defs",)

    @property
    def stem(self) -> str:
        return self.file.removesuffix(".schema.json")

    @property
    def meta(self) -> dict[str, Any] | None:
        m = self.data.get("x-veyltrace")
        return m if isinstance(m, dict) else None

    @property
    def is_contract(self) -> bool:
        return self.meta is not None

    @property
    def kind(self) -> str | None:
        return (self.meta or {}).get("kind")

    @property
    def defs(self) -> dict[str, Any]:
        d: Any = self.data
        for k in self.defs_path:
            d = d.get(k, {}) if isinstance(d, dict) else {}
        return d if isinstance(d, dict) else {}

    @property
    def title_name(self) -> str:
        t = self.data.get("title")
        return t if isinstance(t, str) and PASCAL_RE.match(t) else pascal(self.stem)


@dataclass
class Inputs:
    """Everything the generator reads, keyed deterministically."""

    root: Path
    schemas: dict[str, SchemaFile]  # by file name, sorted
    examples: dict[str, Any]  # by contract name; BROKEN if unparsable
    predicates: Any  # parsed contracts/predicates.json, None if absent, BROKEN if unparsable
    openapi: Any  # parsed packages/gateway/openapi.json, None if absent

    @property
    def contracts(self) -> list[SchemaFile]:
        return sorted((s for s in self.schemas.values() if s.is_contract), key=lambda s: s.stem)


def _no_dupes(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    keys = [k for k, _ in pairs]
    dupes = sorted({k for k in keys if keys.count(k) > 1})
    if dupes:
        raise ValueError(f"duplicate keys {dupes}")
    return dict(pairs)


def _no_constant(name: str) -> Any:
    raise ValueError(f"{name} is not valid JSON")  # json.loads accepts NaN/Infinity by default


def parse_json(raw: bytes, label: str, report: Report) -> Any:
    """Strict JSON: UTF-8, LF only, no duplicate keys, no NaN/Infinity."""
    if b"\r" in raw:
        report.error(f"{label}: CR line endings; contract files use LF")
    try:
        return json.loads(raw.decode("utf-8"), object_pairs_hook=_no_dupes, parse_constant=_no_constant)
    except (UnicodeDecodeError, ValueError) as exc:
        report.error(f"{label}: invalid JSON: {exc}")
        return BROKEN


def load_inputs(root: Path, report: Report) -> Inputs:
    """Read schemas, examples, predicates.json and the optional gateway OpenAPI document."""
    schemas: dict[str, SchemaFile] = {}
    for path in sorted((root / "contracts" / "schemas").glob("*.schema.json"), key=lambda p: p.name):
        raw = path.read_bytes()
        data = parse_json(raw, f"contracts/schemas/{path.name}", report)
        if isinstance(data, dict):
            schemas[path.name] = SchemaFile(path.name, data, raw)
        elif data is not BROKEN:
            report.error(f"contracts/schemas/{path.name}: a schema must be a JSON object")
    if not schemas:
        report.error("no contracts/schemas/*.schema.json found")
    examples: dict[str, Any] = {}
    for path in sorted((root / "contracts" / "examples").glob("*.example.json"), key=lambda p: p.name):
        examples[path.name.removesuffix(".example.json")] = parse_json(
            path.read_bytes(), f"contracts/examples/{path.name}", report
        )
    pred_path = root / "contracts" / "predicates.json"
    predicates = (
        parse_json(pred_path.read_bytes(), "contracts/predicates.json", report) if pred_path.is_file() else None
    )
    api_path = root / "packages" / "gateway" / "openapi.json"
    openapi = parse_json(api_path.read_bytes(), "packages/gateway/openapi.json", report) if api_path.is_file() else None
    return Inputs(root, schemas, examples, predicates, None if openapi is BROKEN else openapi)


# --------------------------------------------------------------------------- helpers


def pascal(name: str) -> str:
    """PascalCase of a def, field or contract name: `case_id` -> `CaseId`; `TimeWindow` is kept."""
    parts = [p for p in re.split(r"[^0-9A-Za-z]+", name) if p]
    out = "".join(p[0].upper() + p[1:] for p in parts) or "X"
    return "N" + out if out[0].isdigit() else out


def const_name(name: str) -> str:
    """Module constant for a contract: `telemetry.metrics` -> `TELEMETRY_METRICS`."""
    return re.sub(r"\W", "_", name).upper()


def py_ident(name: str) -> tuple[str, bool]:
    """Python attribute for a JSON property, and whether it needs an alias.

    `_type` -> `type_`, `predicateType` -> `predicate_type`; keywords and BaseModel names get a trailing `_`.
    """
    ok = re.fullmatch(r"[a-z][a-z0-9_]*", name) and not keyword.iskeyword(name)
    if ok and not name.startswith("model_") and name not in SHADOWED:
        return name, False
    base = re.sub(r"\W", "_", re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)).lower().strip("_") or "field"
    base = "f_" + base if base[0].isdigit() else base
    if name.startswith("_") or keyword.iskeyword(base) or base in SHADOWED or base.startswith("model_"):
        base += "_"
    return base, True


def isort_key(name: str, *, fold: bool = True) -> tuple[int, list[Any]]:
    """ruff's order: SCREAMING_CASE, CamelCase, rest; natural sort, case-folded for isort
    import members, case-sensitive (`fold=False`) for RUF022 `__all__`."""
    group = 0 if len(name) > 1 and name.upper() == name else 1 if name[:1].isupper() else 2
    return group, [int(p) if p.isdigit() else p for p in re.split(r"(\d+)", name.lower() if fold else name)]


def all_key(name: str) -> tuple[int, list[Any]]:
    return isort_key(name, fold=False)


def one_line(text: Any) -> str:
    return " ".join(str(text).split()) if text else ""


def py_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def py_lit(v: Any) -> str:
    """Python literal for a JSON scalar."""
    if v is None or isinstance(v, bool):
        return repr(v)
    if isinstance(v, str):
        return py_str(v)
    if isinstance(v, int | float):
        return repr(v)
    raise GenError(f"unsupported literal {v!r}")


def py_pattern(p: str) -> str:
    """Raw string when possible, so regexes read as written in the schema."""
    return f'r"{p}"' if '"' not in p and not p.endswith("\\") and p.isprintable() else py_str(p)


def resolve_ref(files: dict[str, SchemaFile], sf: SchemaFile, ref: str, where: str) -> tuple[SchemaFile, str | None]:
    """Resolve `<file>#/$defs/<name>`, `#/$defs/<name>` or `<file>` (whole document) without I/O."""
    file, _, frag = ref.partition("#")
    file = file.removeprefix(ID_PREFIX).removeprefix("./")
    target = sf if file == "" else files.get(file)
    if target is None:
        raise GenError(f"{where}: $ref {ref!r}: unknown schema file {file!r}")
    if frag in ("", "/"):
        return target, None
    prefix = "/" + "/".join(target.defs_path) + "/"
    name = frag.removeprefix(prefix).replace("~1", "/").replace("~0", "~")
    if not frag.startswith(prefix) or "/" in frag.removeprefix(prefix) or name not in target.defs:
        raise GenError(f"{where}: $ref {ref!r} does not name an entry of {prefix}")
    return target, name


def deref(files: dict[str, SchemaFile], sf: SchemaFile, s: Any, where: str) -> tuple[SchemaFile, Any]:
    """Follow $ref chains to the target schema."""
    for _ in range(32):
        if not (isinstance(s, dict) and "$ref" in s):
            return sf, s
        sf, name = resolve_ref(files, sf, s["$ref"], where)
        s = sf.data if name is None else sf.defs[name]
    raise GenError(f"{where}: $ref chain too long")


def strip_null(files: dict[str, SchemaFile], sf: SchemaFile, s: Any, where: str) -> tuple[SchemaFile, Any, bool]:
    """Return (file, non-null base schema, nullable) for `T | null` written either way (CONVENTIONS §3.2)."""
    sf, s = deref(files, sf, s, where)
    if not isinstance(s, dict):
        return sf, s, False
    t = s.get("type")
    if isinstance(t, list) and "null" in t:
        rest = [x for x in t if x != "null"]
        return sf, {**s, "type": rest[0] if len(rest) == 1 else rest}, True
    for key in ("anyOf", "oneOf"):
        opts = s.get(key)
        if isinstance(opts, list) and {"type": "null"} in opts:
            rest = [o for o in opts if o != {"type": "null"}]
            if len(rest) == 1:
                sf2, base, _ = strip_null(files, sf, rest[0], where)
                return sf2, base, True
    if isinstance(s.get("enum"), list) and None in s["enum"]:
        return sf, {**s, "enum": [v for v in s["enum"] if v is not None]}, True
    return sf, s, False


def json_base(files: dict[str, SchemaFile], sf: SchemaFile, s: Any, where: str) -> str:
    """Base JSON type of a column: string, integer, number, boolean or array<...>."""
    sf, s, _ = strip_null(files, sf, s, where)
    if not isinstance(s, dict):
        return "?"
    t = s.get("type")
    if t is None and ("enum" in s or "const" in s):
        vals = s.get("enum", [s.get("const")])
        if all(isinstance(v, str) for v in vals):
            return "string"
    if t is None and isinstance(s.get("anyOf"), list):  # e.g. evidence_ref: one of several string formats
        bases = {json_base(files, sf, b, where) for b in s["anyOf"]}
        return bases.pop() if len(bases) == 1 else "?"
    if t == "array":
        return f"array<{json_base(files, sf, s.get('items', {}), where)}>"
    return t if isinstance(t, str) else "?"


# --------------------------------------------------------------------------- validation


def validate(inputs: Inputs, report: Report) -> None:
    """Meta-schema, CONVENTIONS rules, examples and predicates.json (step 2 of the R-01 spec)."""
    files = inputs.schemas
    registry: Registry = Registry().with_resources(
        (sf.data["$id"], DRAFT202012.create_resource(sf.data))
        for sf in files.values()
        if isinstance(sf.data.get("$id"), str)
    )
    valid: set[str] = set()
    for sf in files.values():
        try:
            Draft202012Validator.check_schema(sf.data)
            valid.add(sf.file)
        except SchemaError as exc:
            report.error(f"{sf.file}: not valid JSON Schema 2020-12: {exc.message} at {exc.json_path}")
        try:
            check_conventions(sf, files, report)
        except GenError as exc:
            report.error(str(exc))
    contract_names = {sf.stem for sf in inputs.contracts}
    for sf in inputs.contracts:
        ex, label = example_of(inputs, sf)
        if ex is None:
            report.error(f"{label}: missing (CONVENTIONS §6)")
        elif ex is not BROKEN and sf.file in valid:
            if sf.kind == "json" and not isinstance(ex, dict):
                report.error(f"{label}: must be one object")
            elif sf.kind == "json":
                check_instance(sf, registry, ex, label, report)
            elif not isinstance(ex, list) or not 2 <= len(ex) <= 3:
                report.error(f"{label}: must be an array of 2-3 rows (CONVENTIONS §6)")
            else:
                for i, row in enumerate(ex):
                    check_instance(sf, registry, row, f"{label}[{i}]", report)
    for name in sorted(set(inputs.examples) - contract_names):
        report.warn(f"contracts/examples/{name}.example.json has no contract schema")
    psf = files.get("predicates.schema.json")
    if psf is None:
        report.error("contracts/schemas/predicates.schema.json missing (needed to validate contracts/predicates.json)")
    if inputs.predicates is None:
        report.error("contracts/predicates.json missing (contract_changes B64, lead decision 2.6)")
    elif psf is not None and not psf.is_contract and inputs.predicates is not BROKEN and psf.file in valid:
        check_instance(psf, registry, inputs.predicates, "contracts/predicates.json", report)


def example_of(inputs: Inputs, sf: SchemaFile) -> tuple[Any, str]:
    """(example instance or None, label). A contract whose instance is committed under contracts/
    (predicates -> contracts/predicates.json) uses that file instead of an example."""
    if sf.stem not in inputs.examples and (sf.meta or {}).get("path") == "contracts/predicates.json":
        return inputs.predicates, "contracts/predicates.json"
    return inputs.examples.get(sf.stem), f"contracts/examples/{sf.stem}.example.json"


def check_instance(sf: SchemaFile, registry: Registry, instance: Any, label: str, report: Report) -> None:
    """Validate one instance against a schema; report at most five errors."""
    try:
        errors = sorted(
            Draft202012Validator(sf.data, registry=registry).iter_errors(instance), key=lambda e: e.json_path
        )
    except (Unresolvable, SchemaError) as exc:  # e.g. a $ref that does not resolve
        report.error(f"{label}: cannot validate against {sf.file}: {exc}")
        return
    for e in errors[:5]:
        report.error(f"{label}: {e.json_path}: {e.message}")


def check_conventions(sf: SchemaFile, files: dict[str, SchemaFile], report: Report) -> None:
    """The mechanical rules of CONVENTIONS.md for one schema file."""
    d, err = sf.data, (lambda msg: report.error(f"{sf.file}: {msg}"))
    if d.get("$schema") != META_SCHEMA:
        err(f'"$schema" must be {META_SCHEMA}')
    if d.get("$id") != ID_PREFIX + sf.file:
        err(f'"$id" must be {ID_PREFIX + sf.file} (CONVENTIONS §1)')
    if not (isinstance(d.get("title"), str) and PASCAL_RE.match(d["title"])):
        err('"title" must be a PascalCase model name')
    if not one_line(d.get("description")):
        err('"description" is required')
    meta = d.get("x-veyltrace")
    if sf.stem == "common" and meta is not None:
        err("common.schema.json must not carry x-veyltrace")
    elif meta is None and sf.stem not in SUPPORT:
        err("x-veyltrace block missing (CONVENTIONS §2)")
    elif isinstance(meta, dict):
        check_meta(sf, files, meta, err)
    elif meta is not None:
        err("x-veyltrace must be an object")
    walk(sf, files, d, "#", report, table=sf.kind in TABLE_KINDS, column=False)


def check_meta(sf: SchemaFile, files: dict[str, SchemaFile], meta: dict[str, Any], err: Any) -> None:
    """x-veyltrace block, row/JSON shape, schema_version and x-arrow columns (CONVENTIONS §2-§4)."""
    if unknown := sorted(set(meta) - META_KEYS):
        err(f"x-veyltrace: unknown keys {unknown}")
    if meta.get("name") != sf.stem:
        err(f"x-veyltrace.name must be {sf.stem!r} (the file name)")
    m = VERSION_RE.match(str(meta.get("version", "")))
    if not m or f"{m[1]}.{m[2]}" != SERIES:
        err(f"x-veyltrace.version must be full SemVer {SERIES}.<patch>")
    kind = meta.get("kind")
    if kind not in KINDS:
        err(f"x-veyltrace.kind must be one of {list(KINDS)}")
    if not re.fullmatch(r"[a-z][a-z0-9_]*", str(meta.get("producer", ""))):
        err("x-veyltrace.producer must be a lowercase engine or component name")
    path = meta.get("path")
    if not isinstance(path, str) or not path or "\\" in path or path.startswith("/") or ".." in path.split("/"):
        err("x-veyltrace.path must be a relative POSIX path")
    raw_props = sf.data.get("properties")
    props: dict[str, Any] = raw_props if isinstance(raw_props, dict) else {}
    if sf.data.get("type") != "object":
        err('the root must be "type": "object" (one object, row or line)')
    if kind in TABLE_KINDS or (kind == "jsonl" and ("key" in meta or "unique" in meta)):
        key = meta.get("key")
        if not (
            isinstance(key, list)
            and key
            and all(isinstance(k, str) and k in props for k in key)
            and len(set(key)) == len(key)
        ):
            err("x-veyltrace.key must be a non-empty list of distinct row properties")
        if not isinstance(meta.get("unique"), bool):
            err("x-veyltrace.unique (bool) is required on table kinds")
    elif "key" in meta or "unique" in meta:
        err("x-veyltrace.key/unique are for table kinds only")
    if "self_hash" in meta:
        sh = meta["self_hash"]
        ok = isinstance(sh, dict) and set(sh) <= {"field", "exclude"} and sh.get("field") in props
        if not (ok and isinstance(sh.get("exclude", []), list) and all(x in props for x in sh.get("exclude", []))):
            err('x-veyltrace.self_hash must be {"field": <property>, "exclude": [<property>...]}')
    title = str(sf.data.get("title", ""))
    if (kind in TABLE_KINDS and not title.endswith("Row")) or (kind == "jsonl" and not title.endswith(("Row", "Line"))):
        err("table contracts are titled <Name>Row (JSONL: <Name>Line), CONVENTIONS §1")
    if kind == "json" and sf.stem not in NO_SCHEMA_VERSION:
        first = next(iter(props), None)
        _, sv = deref(files, sf, props.get("schema_version"), sf.file)
        pattern = "^" + re.escape(SERIES) + r"\.[0-9]+$"
        if first != "schema_version" or not isinstance(sv, dict) or sv.get("pattern") != pattern:
            err(f'JSON contracts start with "schema_version" (string, pattern {pattern}), CONVENTIONS §3.6')
    if kind in TABLE_KINDS:
        for name, ps in props.items():
            xa = ps.get("x-arrow") if isinstance(ps, dict) else None
            if xa not in ARROW:
                err(f"column {name!r}: x-arrow must be one of {list(ARROW)}")
            elif (base := json_base(files, sf, ps, f"{sf.file}#/properties/{name}")) != ARROW[xa][0]:
                err(f"column {name!r}: x-arrow {xa} does not match JSON type {base}")


def walk(
    sf: SchemaFile, files: dict[str, SchemaFile], s: Any, ptr: str, report: Report, *, table: bool, column: bool
) -> None:
    """Object, x-sort, x-order and x-arrow rules on every structural subschema (conditionals skipped)."""
    if not isinstance(s, dict):
        return
    where = f"{sf.file}{ptr}"
    typ = s.get("type")
    tl: list[Any] = typ if isinstance(typ, list) else [typ]
    if "properties" in s or "object" in tl:
        props, ap = s.get("properties"), s.get("additionalProperties")
        if "object" not in tl:
            report.error(f'{where}: objects need "type": "object"')
        if isinstance(props, dict):
            if ap is not False:
                report.error(f"{where}: additionalProperties must be false (CONVENTIONS §3.1)")
            if s.get("required") != sorted(props):
                report.error(f"{where}: required must list every property, sorted (CONVENTIONS §3.1)")
        elif ap is not False and not isinstance(ap, dict):
            report.error(
                f"{where}: an object needs properties or an additionalProperties map schema (CONVENTIONS §3.3)"
            )
    if ("x-sort" in s or "x-order" in s) and "array" not in tl:
        report.error(f"{where}: x-sort/x-order are only allowed on arrays")
    if "x-sort" in s:
        check_sort(sf, files, s, where, report)
    if "x-order" in s and (s["x-order"] != "semantic" or "x-sort" in s):
        report.error(f'{where}: x-order must be "semantic" and excludes x-sort')
    if "x-arrow" in s and not column:
        report.error(f"{where}: x-arrow is only allowed on table columns")
    for k, v in (s.get("properties") or {}).items():
        walk(sf, files, v, f"{ptr}/properties/{k}", report, table=False, column=table and ptr == "#")
    for k, v in (s.get("$defs") or {}).items():
        walk(sf, files, v, f"{ptr}/$defs/{k}", report, table=False, column=False)
    children = [("items", s.get("items")), ("additionalProperties", s.get("additionalProperties"))]
    for key in ("prefixItems", "anyOf", "oneOf"):
        children += [(f"{key}/{i}", v) for i, v in enumerate(s.get(key) or [])]
    for sub, v in children:
        walk(sf, files, v, f"{ptr}/{sub}", report, table=False, column=False)


def check_sort(sf: SchemaFile, files: dict[str, SchemaFile], s: dict[str, Any], where: str, report: Report) -> None:
    """x-sort grammar: [{pointer, order: asc|desc|enum, round?: int, nulls?: first|last}] (lead decision 2.7).

    order "enum" sorts by the value's position in the target's enum (e.g. trial ids T1 < T2 < … < T10,
    which byte order would get wrong); the pointer must resolve to an enum-typed value.
    """
    spec = s["x-sort"]
    if not isinstance(spec, list) or not spec:
        report.error(f"{where}: x-sort must be a non-empty list")
        return
    item_sf, items, _ = strip_null(files, sf, s.get("items", {}), where)
    for i, e in enumerate(spec):
        at = f"{where}: x-sort[{i}]"
        if not isinstance(e, dict) or not {"pointer", "order"} <= set(e) <= {"pointer", "order", "round", "nulls"}:
            report.error(f"{at}: needs pointer and order; optional round, nulls")
            continue
        if e["order"] not in ("asc", "desc", "enum"):
            report.error(f'{at}: order must be "asc", "desc" or "enum"')
        if "round" in e and type(e["round"]) is not int:
            report.error(f"{at}: round must be an integer")
        if e.get("nulls", "first") not in ("first", "last"):
            report.error(f'{at}: nulls must be "first" or "last"')
        if e["pointer"] == ".":
            if isinstance(items, dict) and "properties" in items:
                report.error(f'{at}: pointer "." sorts scalar items; these items are objects')
            elif e["order"] == "enum" and not (isinstance(items, dict) and "enum" in items):
                report.error(f'{at}: order "enum" needs enum-typed items')
            continue
        node_sf, node = item_sf, items  # a field, or a /-separated path into nested objects
        resolved = True
        for seg in str(e["pointer"]).split("/"):
            props = node.get("properties") if isinstance(node, dict) else None
            if not isinstance(props, dict) or seg.replace("~1", "/").replace("~0", "~") not in props:
                report.error(f"{at}: pointer {e['pointer']!r} does not name a field of the items")
                resolved = False
                break
            node_sf, node, _ = strip_null(files, node_sf, props[seg.replace("~1", "/").replace("~0", "~")], where)
        if resolved and e["order"] == "enum" and not (isinstance(node, dict) and "enum" in node):
            report.error(f'{at}: order "enum" needs the pointer to resolve to an enum-typed field')


