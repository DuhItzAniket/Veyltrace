def locate_predicates(inputs: Inputs, psf: SchemaFile) -> tuple[Any, str, list[Any], list[tuple[str, Any]]]:
    """Find the predicate-entry schema in predicates.schema.json: (schema, pointer, entries, scalar constants)."""
    files, data, where = inputs.schemas, inputs.predicates, psf.file
    root = psf.data
    if root.get("type") == "array":
        return root.get("items", {}), "#/items", list(data), []

    def items_of(prop: Any) -> Any:
        arr = deref(files, psf, prop, where)[1]
        return arr.get("items") if isinstance(arr, dict) and arr.get("type") == "array" else None

    props = root.get("properties") or {}
    arrays = [k for k, v in props.items() if is_class(deref(files, psf, items_of(v), where)[1])]
    if len(arrays) != 1 or not isinstance(data, dict):
        raise GenError("predicates.schema.json: expected exactly one array-of-objects property holding the predicates")
    k = arrays[0]
    consts = [(n, data[n]) for n in props if n != k and isinstance(data.get(n), str | int | float | bool)]
    return items_of(props[k]), f"#/properties/{k}/items", list(data.get(k, [])), consts


def py_value(t: T, v: Any, named: dict[str, Named]) -> str | G:
    """Python expression constructing JSON value `v` as type `t` (frozen dataclasses, tuples)."""
    if t.kind == "union":  # null, or the first branch whose JSON shape fits
        shape = {dict: ("ref", "map"), list: ("list", "tuple")}.get(
            type(v), ("str", "int", "float", "bool", "lit", "any")
        )
        t = T("null") if v is None else next((a for a in t.args if a.kind in shape), T("any"))
    if t.kind == "ref" and named[t.args[0]].fields is None:
        return py_value(named[t.args[0]].alias or T("any"), v, named)
    if t.kind in ("ref", "map") and isinstance(v, dict):
        if t.kind == "map":
            return G("{", tuple(prefixed(f"{py_str(k)}: ", py_value(t.args[0], x, named)) for k, x in v.items()), "}")
        n = named[t.args[0]]
        args = (
            prefixed(f"{py_ident(p.json_name)[0]}=", py_value(p.type, v.get(p.json_name), named))
            for p in n.fields or []
        )
        return G(f"{n.name}(", tuple(args), ")")
    if t.kind in ("list", "tuple") and isinstance(v, list):
        sub = [t.args[0]] * len(v) if t.kind == "list" else list(t.args)
        return tuple_doc([py_value(a, x, named) for a, x in zip(sub, v, strict=True)])
    if isinstance(v, list | dict) or t.kind in ("ref", "map", "list", "tuple"):
        raise GenError(f"predicates.json: cannot render {v!r} as {t.kind}")
    return py_lit(v)


def render_predicates(inputs: Inputs) -> str:
    """predicates.py: PREDICATES tuple of frozen dataclasses typed from predicates.schema.json."""
    head = [f"# {HEADER}", '"""Claim-check predicate library (03 §7), generated from contracts/predicates.json."""']
    psf = inputs.schemas.get("predicates.schema.json")
    if psf is None or inputs.predicates is None or inputs.predicates is BROKEN:
        return "\n".join([*head, "", "PREDICATES: tuple[object, ...] = ()", ""])
    item_schema, ptr, entries, consts = locate_predicates(inputs, psf)
    b = Builder(inputs.schemas, inline=True)
    t = b.ir(item_schema, psf, ptr, "PredicateSpec")
    if t.kind != "ref":
        raise GenError("predicates.schema.json: predicate entries must be objects")
    used: set[str] = set()
    blocks: list[tuple[bool, str]] = []
    for n in ordered(b.named):
        lines = ["@dataclass(frozen=True)", f"class {n.name}:", docstring(n.doc, 4)]
        for p in n.fields or []:
            name = py_ident(p.json_name)[0]
            lines += [""] if len(lines) == 3 else []
            lines.append(f"    {name}: " + render(py_doc(p.type, used, plain=True), 4, len(name) + 6))
        blocks.append((True, "\n".join(lines)))
    blocks += [(False, f"{const_name(k)} = {py_lit(v)}") for k, v in consts]
    prefix = f"PREDICATES: tuple[{t.args[0]}, ...] = "
    values = G("(", tuple(py_value(t, e, b.named) for e in entries), ")", tuple1=True) if entries else "()"
    blocks.append((False, prefix + render(values, 0, len(prefix))))
    imports = ["from dataclasses import dataclass"]
    imports += ["from collections.abc import Mapping"] if "Mapping" in used else []
    imports += ["from typing import Literal"] if "Literal" in used else []
    return "\n".join([*head, "", *sorted(imports)]) + "\n\n\n" + join_blocks(blocks) + "\n"


