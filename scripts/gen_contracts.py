"""Generate and check the Veyltrace contract models from contracts/schemas/ (R-01).

Usage:
  uv run scripts/gen_contracts.py                         # validate, then write contracts/generated/
  uv run scripts/gen_contracts.py --check                 # CI: regenerate into a temp dir, byte-compare,
                                                          # round-trip examples, 03 parity report
  uv run scripts/gen_contracts.py --check --strict-parity # also fail on 03 field drift

A custom generator for the schema subset of contracts/schemas/CONVENTIONS.md (no
datamodel-code-generator, no Node). Inputs: contracts/schemas/*.schema.json,
contracts/predicates.json, contracts/examples/*.example.json and, when present,
packages/gateway/openapi.json. Outputs: contracts/generated/python/ (package
veyltrace-contracts) and contracts/generated/ts/. Output is byte-deterministic (sorted,
LF, UTF-8, no timestamps); keywords outside the subset fail loudly instead of being
guessed. Exit codes: 0 ok, 1 validation, diff or round-trip failure, 2 usage.
"""

