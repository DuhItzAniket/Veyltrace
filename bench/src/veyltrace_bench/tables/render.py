"""A generated table and its two renderings: Markdown (`bench/results/tables/*.md`, reviewed in
the repo) and LaTeX (`*.tex`, copied to `paper/generated/` by R-18), per 11 §10.

Both renderings carry the same cells, notes and sources. Notes are numbered by first appearance
in row order and shared by identical text, so a reason printed in many cells is listed once. The
sources list names, for every experiment a table cites, its full code commit and the SHA-256 of
its three result files, or the reason it is not run (04 §10.2 traceability). Output is LF text
with no timestamp and no path, so it depends only on the results.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass

from veyltrace_bench.tables.cells import Cell
from veyltrace_bench.tables.results import Results

GENERATED = "Generated by `veyltrace bench tables` (R-17) from bench/results; never edit by hand."
SOURCE_COLUMN = "Source"


@dataclass(frozen=True)
class Row:
    """One table row: its cells and the experiment its values come from (None for a row of a
    measurement bench does not make, such as replay rates); `also` are experiments a cell names
    explicitly as "(from <id>)", which the sources list then covers too."""

    cells: tuple[Cell, ...]
    source: Results | None
    also: tuple[Results, ...] = ()


@dataclass(frozen=True)
class Table:
    """A paper table: `name` is the file stem, `caption` states the protocol (04 §10.4)."""

    name: str
    title: str
    caption: str
    columns: tuple[str, ...]
    rows: tuple[Row, ...]
    key: tuple[int, ...] = (0,)  # the cells naming a row across an experiment and its revision

    def __post_init__(self) -> None:
        if any(len(row.cells) != len(self.columns) for row in self.rows):
            raise ValueError(f"table {self.name}: a row's cells do not match its {len(self.columns)} columns")

    @property
    def sources(self) -> tuple[Results, ...]:
        """The cited experiments, one each, sorted by id."""
        cited = {s.experiment_id: s for r in self.rows for s in (r.source, *r.also) if s is not None}
        return tuple(cited[k] for k in sorted(cited))


class _Notes:
    """Note numbers by first appearance; a cell's text gets the note's marker appended (a
    superscript in both, so it never reads as an interval; Markdown uses `<sup>`, not GFM
    footnotes, whose `[^n]: text` definitions link checkers read as broken links)."""

    def __init__(self, marker: Callable[[int], str]) -> None:
        self.texts: list[str] = []
        self.marker = marker

    def mark(self, cell: Cell, escape: Callable[[str], str]) -> str:
        if cell.note is None:
            return escape(cell.text)
        if cell.note not in self.texts:
            self.texts.append(cell.note)
        return escape(cell.text) + self.marker(self.texts.index(cell.note) + 1)


TEX_HASH = 12  # SHA-256 prefix in LaTeX, where 64 hex digits overflow a column; the .md has all


def _source_lines(table: Table, digits: int = 64) -> list[str]:
    if not table.sources:
        return [f"none: every row has {NO_SOURCE}"]
    lines: list[str] = []
    for src in table.sources:
        name = f"{src.experiment_id} ({src.role})" if src.role else src.experiment_id
        if src.reason is not None:
            line = f"{name}: not run: {src.reason.removeprefix('not run: ')}"
        else:
            files = ", ".join(f"{file} {sha[:digits]}" for file, sha in src.hashes)
            line = f"{name}: commit {src.commit}; sha256 {files}"
        lines.append(f"{line}; protocol: {src.protocol}" if src.protocol else line)  # 04 §10.4
    return lines


NO_SOURCE = "no bench experiment"


def _cells(table: Table, notes: _Notes, escape: Callable[[str], str]) -> list[list[str]]:
    return [
        [*(notes.mark(c, escape) for c in row.cells), escape(row.source.label if row.source else NO_SOURCE)]
        for row in table.rows
    ]


def _md_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace("|", "\\|")


def markdown(table: Table) -> str:
    """The Markdown table, its notes and its sources."""
    notes = _Notes(lambda i: f"<sup>{i}</sup>")
    body = _cells(table, notes, _md_escape)
    columns = [*table.columns, SOURCE_COLUMN]
    lines = [f"<!-- {GENERATED} -->", "", f"# {table.title}", "", table.caption, ""]
    lines += ["| " + " | ".join(_md_escape(c) for c in columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(row) + " |" for row in body]
    if notes.texts:
        lines += ["", "Notes:", ""] + [f"{i}. {_md_escape(n)}" for i, n in enumerate(notes.texts, 1)]
    lines += ["", "Sources:", ""] + [f"- {_md_escape(s)}" for s in _source_lines(table)]
    return "\n".join(lines) + "\n"


#: Characters LaTeX treats specially, and the non-ASCII ones our text uses that pdflatex lacks.
_TEX = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
    "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "§": r"\S{}",
    "−": "$-$", "–": "--", "—": "---", "≥": r"$\geq$", "≤": r"$\leq$", "±": r"$\pm$",
    "×": r"$\times$", "→": r"$\rightarrow$", "≈": r"$\approx$", "`": "",
    "|": r"\textbar{}", "<": r"\textless{}", ">": r"\textgreater{}",
}  # fmt: skip


def tex_escape(value: str) -> str:
    return "".join(_TEX.get(ch, ch) for ch in value)


def latex(table: Table) -> str:
    """A `table` float with a plain `tabular` (no package beyond the LaTeX kernel), notes and
    sources as footnote-size text below it; R-18 places and sizes it in the paper."""
    notes = _Notes(lambda i: rf"\textsuperscript{{{i}}}")
    body = _cells(table, notes, tex_escape)
    columns = [*table.columns, SOURCE_COLUMN]
    lines = [
        f"% {GENERATED}",
        r"\begin{table}[t]",
        r"\centering",
        rf"\caption{{{tex_escape(table.title)}. {tex_escape(table.caption)}}}",
        rf"\label{{tab:{table.name}}}",
        r"\small",
        rf"\begin{{tabular}}{{{'l' * len(columns)}}}",
        r"\hline",
        " & ".join(tex_escape(c) for c in columns) + r" \\",
        r"\hline",
        *(" & ".join(row) + r" \\" for row in body),
        r"\hline",
        r"\end{tabular}",
        r"\par\smallskip\footnotesize",
    ]
    lines += [rf"\textsuperscript{{{i}}} {tex_escape(n)}\\" for i, n in enumerate(notes.texts, 1)]
    lines += [rf"Source: {tex_escape(s)}\\" for s in _source_lines(table, TEX_HASH)]
    lines.append(r"\end{table}")
    return "\n".join(lines) + "\n"
